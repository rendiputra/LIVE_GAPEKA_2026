"""Generate docs/verification_status.md from the verification records.

The single source of truth is ``data/review/verifications.json`` plus the golden
fixtures. This report exists so that "verified" never drifts from evidence: a
human must have compared a named artefact, and the record must say so.

Regenerate on every report run.

Usage:
    python -m pipeline.verification_status
"""

from __future__ import annotations

import json
from pathlib import Path

DB = Path("data/gapeka.db")
VERIFICATIONS = Path("data/review/verifications.json")
GOLDEN_DIR = Path("tests/golden")
DOCS = Path("docs")


def load_records() -> list[dict]:
    if not VERIFICATIONS.exists():
        return []
    return json.loads(VERIFICATIONS.read_text(encoding="utf-8")).get("records", [])


def load_golden() -> list[dict]:
    records = []
    patterns = ("*_golden.json", "verified_*.json")
    paths = sorted({path for pattern in patterns for path in GOLDEN_DIR.glob(pattern)})
    for path in paths:
        payload = json.loads(path.read_text(encoding="utf-8"))
        records.append(
            {
                "file": path.name,
                "verified_by_human": payload.get("verified_by_human", False),
                "verifier": payload.get("verifier"),
                "date": payload.get("date"),
                "method": payload.get("method"),
                "scope": payload.get("scope", {}),
                "trains": [t.get("train_no") for t in payload.get("trains", [])],
                "stops": sum(len(t.get("stops", [])) for t in payload.get("trains", [])),
                "trip_ids": [
                    t.get("trip_id") for t in payload.get("trains", []) if t.get("trip_id")
                ],
            }
        )
    return records


def parse_state() -> dict:
    """What the parser currently holds, per book."""
    state: dict[str, dict] = {}
    for book, parsed, validated in (
        (
            "Book 1 (intercity)",
            "data/parsed/intercity_trips.json",
            "data/validated/intercity_book1.json",
        ),
        ("Book 2 (local)", "data/parsed/local_trips.json", "data/validated/local_book2.json"),
    ):
        entry = {"trains": None, "stops": None, "validated": None, "pages": None}
        if Path(parsed).exists():
            payload = json.loads(Path(parsed).read_text(encoding="utf-8"))
            trains = payload["trains"]
            entry["trains"] = len(trains)
            entry["stops"] = sum(len(t["stops"]) for t in trains)
            pages: set[int] = set()
            for train in trains:
                pages.update(stop["provenance"]["page"] for stop in train["stops"])
            entry["pages"] = sorted(pages)
        if Path(validated).exists():
            entry["validated"] = json.loads(Path(validated).read_text(encoding="utf-8"))["count"]
        state[book] = entry
    return state


def render() -> str:
    records = load_records()
    golden = load_golden()
    state = parse_state()

    lines: list[str] = []
    add = lines.append
    add("# Verification status")
    add("")
    add("> Generated by `python -m pipeline.verification_status` from")
    add("> `data/review/verifications.json` and `tests/golden/`. Do not edit by hand.")
    add("")
    add(
        "A train is described as *human-verified* only when a record below names the "
        "artefact compared and the scope. Everything else is **parsed, not verified**."
    )
    add("")

    add("## Human-verified records")
    add("")
    if not records:
        add("None.")
    else:
        add("| Verifier | Date | Method | Pages | Trains | Rows | Scope detail | Artefact |")
        add("|---|---|---|---|---|---|---|---|")
        for record in records:
            scope = record.get("scope", {})
            pages = ", ".join(str(p) for p in scope.get("pages", []))
            trains = ", ".join(scope.get("trains", []))
            rows = scope.get("rows", "all rows in scope")
            detail_parts = []
            if scope.get("stations"):
                detail_parts.append("stations " + ", ".join(scope["stations"]))
            if scope.get("osm_node"):
                detail_parts.append(f"OSM node {scope['osm_node']}")
            add(
                f"| {record.get('verifier')} | {record.get('date')} | "
                f"{record.get('method')} | {pages} | {trains} | {rows} | "
                f"{'; '.join(detail_parts)} | `{record.get('artefact')}` |"
            )
    add("")

    add("## Golden fixtures")
    add("")
    if not golden:
        add("None.")
    else:
        add("| File | Human-verified | Trains | Stops | Scope note |")
        add("|---|---|---|---|---|")
        for record in golden:
            note = record["scope"].get("note", "")
            add(
                f"| `{record['file']}` | {record['verified_by_human']} | "
                f"{', '.join(str(t) for t in record['trains'])} | {record['stops']} | "
                f"{note} |"
            )
    add("")

    add("## Not yet verified, per book")
    add("")
    add("| Book | Trains parsed | Stops parsed | Validated | Human-verified trains |")
    add("|---|---|---|---|---|")
    # Verified trips per book, from the DB when it is available: a fixture names a
    # trip_id, and the DB says which book that trip belongs to.
    verified_by_book: dict[str, int] = {}
    verified_total = 0
    if DB.exists():
        import sqlite3

        connection = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
        try:
            for record in golden:
                if not record["verified_by_human"]:
                    continue
                for trip_id in record.get("trip_ids", []):
                    row = connection.execute(
                        "SELECT book FROM trips WHERE trip_id = ?", (trip_id,)
                    ).fetchone()
                    if row is None:
                        continue
                    verified_total += 1
                    key = "Book 1 (intercity)" if row[0] == 1 else "Book 2 (local)"
                    verified_by_book[key] = verified_by_book.get(key, 0) + 1
        finally:
            connection.close()

    for book, entry in state.items():
        count = verified_by_book.get(book)
        label = f"{count} trips verified end to end" if count is not None else "not measured"
        add(f"| {book} | {entry['trains']} | {entry['stops']} | {entry['validated']} | {label} |")
    add("")
    add(
        "The counts above are what the pipeline holds. They are **not** a claim of "
        "correctness: only the records in the first table are human-checked."
    )
    add("")
    add("## Engine artefacts (Phase 5) — not verified")
    add("")
    add("These exist so a human can check the engine against the PDF. None is evidence of")
    add("correctness, and none is human-verified.")
    add("")
    add("| Artefact | What it is | Human-verified |")
    add("|---|---|---|")
    for name, what in (
        (
            "`engine/golden_frames.json`",
            "sampled frames for browser-port parity (trip, t, lat, lon, s_m, status)",
        ),
        (
            "`data/review/engine_replay.html`",
            "Leaflet replay page, 30 s frames for 2026-12-01",
        ),
        (
            "`data/review/r1_engine_sweep.json`",
            "24 h sweep: active counts, off-polyline, continuity, benchmark",
        ),
        (
            "`data/review/suspect_segments_review.html`",
            "routed vs straight geometry for suspect segments; no decision",
        ),
        (
            "`data/review/coverage_blockers.json`",
            "why trips are hidden and which blocker would unblock most",
        ),
        (
            "`data/review/h5_h6_gate.json`",
            "rail-path gate evidence for the H5/H6 coordinates",
        ),
    ):
        add(f"| {name} | {what} | No |")
    add("")
    add("## What is explicitly out of scope")
    add("")
    add("- KRL (approx. PDF 812-1513) and freight (approx. 1514-1673) are not parsed.")
    add("- Book 1 and Book 2 samples generated for review have not been compared by a human.")
    add("- Station coordinates come from external sources; they are not verified.")
    add("- Engine positions are a schedule estimate; none has been compared with a real train.")
    add("")
    return "\n".join(lines) + "\n"


def main() -> int:
    DOCS.mkdir(parents=True, exist_ok=True)
    target = DOCS / "verification_status.md"
    target.write_text(render(), encoding="utf-8")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
