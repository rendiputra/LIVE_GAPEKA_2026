"""Phase 6b report: verification sheet, V15, snap audit, export, basemap, UI.

Every number is read from a generated file.

Usage:
    python -m pipeline.phase6b_report
"""

from __future__ import annotations

import json
from pathlib import Path

REVIEW = Path("data/review")
DOCS = Path("docs")


def load(path: Path, default=None):
    if not path.exists():
        return default
    return json.loads(path.read_text(encoding="utf-8"))


def main() -> int:
    selection = load(REVIEW / "verification_selection.json", {})
    v15 = load(REVIEW / "v15_endpoints.json", {})
    audit = load(REVIEW / "snap_audit.json", {})
    export = load(REVIEW / "web_export.json", {})
    bench = load(REVIEW / "web_bench.json", {})
    lighthouse = load(REVIEW / "lighthouse.json", {})
    axe = load(REVIEW / "axe_report.json", {})
    tz = load(REVIEW / "timezone_parity.json", [])
    findings = load(REVIEW / "verification_findings.json", {"findings": []})

    lines: list[str] = []
    add = lines.append

    add("# Phase 6b — verification, cross-checks, basemap, readiness")
    add("")
    add("> Generated by `python -m pipeline.phase6b_report`. Do not edit by hand.")
    add("> Nothing here is described as *verified* unless `verifications.json` says so.")
    add("")

    add("## T1 — Human verification sheet")
    add("")
    if selection:
        add(f"Selection seed `{selection['seed']}`, **{len(selection['trains'])}** trains.")
        add("")
        add("| Stratum | Covered | Required |")
        add("|---|---|---|")
        for key, need in selection["requirements"].items():
            got = selection["strata"].get(key, 0)
            add(f"| {key} | {got} | {need} |")
        add("")
        add("| # | KA | Book | Class | Status | Reason |")
        add("|---|---|---|---|---|---|")
        for index, train in enumerate(selection["trains"], start=1):
            add(
                f"| {index} | {train['train_no']} | {train['book']} | "
                f"{train['service_class']} | {train['status']} | {train['reason']} |"
            )
        add("")
    add(
        "Sheet: `data/review/verification_sheet.html` (self-contained, no network). "
        "Import: `python -m pipeline.import_verifications <file>`."
    )
    add("")
    open_findings = [f for f in findings.get("findings", []) if f.get("status") == "open"]
    add(f"Open verification findings: **{len(open_findings)}**.")
    add("")

    add("## T2 — V15 endpoint cross-check")
    add("")
    if v15:
        add(f"Trips compared: **{v15['summary']['trips']}** (parsed vs index and summary tables).")
        add("")
        add("| Source | Compared | Exact | Within 1 min | Larger | Absent |")
        add("|---|---|---|---|---|---|")
        for name, counts in v15["summary"]["per_source"].items():
            add(
                f"| {name} | {counts['compared']} | {counts['exact']} | "
                f"{counts['within_1min']} | {counts['larger']} | {counts['absent']} |"
            )
        add("")
        add(f"Larger differences: **{len(v15['summary']['larger'])}**. Nothing auto-resolved.")
        add("")

    add("## T3 — Station snap audit")
    add("")
    if audit:
        dist = audit["distribution_m"]
        add(f"Stations: **{audit['stations_total']}**, routable **{audit['routable_total']}**.")
        add("")
        add("| Metric | Value |")
        add("|---|---|")
        add(f"| max snap | {dist['max']} m |")
        add(f"| p99 | {dist['p99']} m |")
        add(f"| p95 | {dist['p95']} m |")
        add(f"| median | {dist['median']} m |")
        add(f"| above {audit['warn_threshold_m']:.0f} m | {len(audit['over_100m'])} |")
        add("")
        if audit["over_100m"]:
            add("| Code | Snap (m) | Status | Source |")
            add("|---|---|---|---|")
            for row in audit["over_100m"]:
                add(
                    f"| {row['code']} | {row['snap_distance_m']} | {row['coord_status']} | "
                    f"{row['coord_source']} {row['coord_source_id']} |"
                )
            add("")

    add("## T4 — Export after dedupe")
    add("")
    if export:
        add(f"Content hash `{export['content_hash']}`.")
        add("")
        add("| File | Raw kB | Gzip kB |")
        add("|---|---|---|")
        for name, size in export["sizes"].items():
            add(f"| {name} | {size['raw'] / 1024:.1f} | {size['gzip'] / 1024:.1f} |")
        add("")
        add(
            f"Segments **{export['segments']}** (was 782 before the dedupe), trips "
            f"**{export['trips']}**, stations **{export['stations']}**."
        )
        add("")

    add("## T5 — Basemap")
    add("")
    tiles = load(Path("web/public/tiles/manifest.json"), {})
    assets = load(Path("web/public/tiles/assets/manifest.json"), {})
    if tiles:
        add("| Field | Value |")
        add("|---|---|")
        add(f"| file | `{tiles['file']}` |")
        add(f"| size | **{tiles['megabytes']} MB** |")
        add(f"| build date | {tiles['build_date']} |")
        add(f"| OSM data time | {tiles['osm_data_time']} |")
        add(f"| bbox | {tiles['bbox']} |")
        add(f"| zoom | {tiles['min_zoom']}-{tiles['max_zoom']} |")
        add("")
    else:
        add("Run `make basemap` first (requires the network).")
        add("")
    if assets:
        add(
            f"Self-hosted glyphs and sprites: **{assets['files']}** files, "
            f"{assets['megabytes']} MB. No runtime CDN."
        )
        add("")

    add("## T6/T7 — UI and robustness")
    add("")
    if bench:
        add(
            f"Frame time: median **{bench['median_ms']:.2f} ms**, p95 "
            f"{bench['p95_ms']:.2f} ms, max {bench['max_trains']} trains on screen."
        )
        add("")
    if tz:
        add("Timezone parity (same instant, three browser timezones):")
        add("")
        add("| Timezone | Status line | Panel rows |")
        add("|---|---|---|")
        for record in tz:
            add(f"| {record['timezoneId']} | `{record['status']}` | {len(record['rows'])} |")
        add("")
    if axe:
        add(f"axe serious/critical violations: **{axe.get('serious_or_critical', 'n/a')}**.")
        add("")
    if lighthouse:
        scores = lighthouse.get("scores", {})
        metrics = lighthouse.get("metrics", {})
        add("| Lighthouse (mobile) | Value |")
        add("|---|---|")
        for key, value in scores.items():
            add(f"| {key} | {value} |")
        add(f"| LCP | {metrics.get('largest_contentful_paint_ms', 0):.0f} ms |")
        add(f"| TBT | {metrics.get('total_blocking_time_ms', 0):.0f} ms |")
        add(f"| CLS | {metrics.get('cumulative_layout_shift', 0):.3f} |")
        add(f"| total bytes | {metrics.get('total_byte_weight', 0) / 1024:.0f} kB |")
        add("")
        add("Report only, measured with tiles stubbed (see `data/review/lighthouse.json`).")
        add("")

    add("## Launch readiness (Phase 7 gates)")
    add("")
    add("| Gate | State |")
    add("|---|---|")
    add("| 20 trains verified | **pending** — the sheet is ready for the human |")
    add(
        f"| no open findings | {'yes' if not open_findings else f'**{len(open_findings)} open**'} |"
    )
    add("| tiles live, not public OSM | **pending hosting** — extract built |")
    add("| legal items closed | **no** — items 1 and 2 open |")
    add("| disclaimer/banner | yes (Playwright) |")
    add("| parity exact | yes (6,000 samples) |")
    add(f"| Lighthouse/axe | recorded (axe serious {axe.get('serious_or_critical', '?')}) |")
    add("| reproducible | see `make reproduce` output |")
    add("| deploy dry-run | **not done** |")
    add("")

    DOCS.mkdir(parents=True, exist_ok=True)
    target = DOCS / "phase6b_report.md"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
