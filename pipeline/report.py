def _ranges(pages: list[int]) -> str:
    """Compress a sorted page list into '1-5, 7, 9-12'."""
    if not pages:
        return "-"
    ordered = sorted(pages)
    spans: list[tuple[int, int]] = []
    start = prev = ordered[0]
    for page in ordered[1:]:
        if page == prev + 1:
            prev = page
            continue
        spans.append((start, prev))
        start = prev = page
    spans.append((start, prev))
    return ", ".join(f"{a}-{b}" if a != b else str(a) for a, b in spans)


def _median(values: list[float]) -> float:
    return statistics.median(values) if values else 0.0


def _table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out.extend("| " + " | ".join(row) + " |" for row in rows)
    return "\n".join(out)


def _offset_runs(pages: list[dict]) -> list[tuple[int, int, int]]:
    """Return (start_page, end_page, offset) runs of a stable printed-page offset.

    Pages whose printed number could not be read are skipped; runs with the same
    offset are merged so the table shows book boundaries, not extraction gaps.
    """
    runs: list[tuple[int, int, int]] = []
    current: tuple[int, int, int] | None = None
    for p in pages:
        printed = p["printed_page"]
        if printed is None or not printed.isdigit():
            continue
        offset = p["page"] - int(printed)
        if current and current[2] == offset:
            current = (current[0], p["page"], offset)
            continue
        if current:
            runs.append(current)
        current = (p["page"], p["page"], offset)
    if current:
        runs.append(current)
    return [r for r in runs if r[1] - r[0] + 1 >= MIN_OFFSET_RUN]


def render_report(inventory: dict) -> str:
    pages: list[dict] = inventory["pages"]
    source = inventory["source"]
    summary = inventory["summary"]
    total = source["page_count"]

    by_type = Counter(p["type"] for p in pages)
    by_section = Counter(p["section"] for p in pages)
    by_subtype = Counter((p["section"], p["type"], p["subtype"]) for p in pages)
    by_rule = Counter(p["rule"] for p in pages)
    by_confidence = Counter(p["confidence"] for p in pages)
    index = {p["page"]: p for p in pages}

    lines: list[str] = []
    add = lines.append

    add("# Gapeka 2026 — Phase 0 Inventory Report")
    add("")
    add("> Generated by `python -m pipeline.inventory`. Do not edit by hand.")
    add("> Classification is **not verified**. Accuracy is confirmed only by human spot-check.")
    add("")
    add("## 1. Source")
    add("")
    add(
        _table(
            ["Field", "Value"],
            [
                ["Path", f"`{source['path']}`"],
                ["SHA-256", f"`{source['sha256']}`"],
                ["Size", f"{source['size_bytes']:,} bytes"],
                ["Pages", f"{total:,}"],
                ["PyMuPDF", inventory["tool"]["pymupdf"]],
                ["Python", inventory["tool"]["python"]],
            ],
        )
    )
    add("")
    add(
        'AGENTS.md section 1 said "~1100 pages, 64 MB". The real document is '
        f"**{total:,} pages / {source['size_bytes'] / 1_000_000:.1f} MB**. "
        "The document is titled *Jaringan Jalur Kereta Api Nasional **di Jawa***, "
        "so every phase is Java-only."
    )
    add("")

    add("## 2. Page counts per type")
    add("")
    add(
        _table(
            ["Type", "Pages", "Share"],
            [[t, f"{by_type.get(t, 0):,}", f"{by_type.get(t, 0) / total:.1%}"] for t in PAGE_TYPES]
            + [["**total**", f"**{total:,}**", "**100.0%**"]],
        )
    )
    add("")
    add(
        "`legend` is empty: the only legend in the document is embedded in the last "
        "stringline page (PDF page 51), not printed on its own page."
    )
    add("")

    add("## 3. Page counts per section")
    add("")
    add(
        _table(
            ["Section", "Pages", "PDF range"],
            [
                [
                    s,
                    f"{by_section.get(s, 0):,}",
                    _ranges([p["page"] for p in pages if p["section"] == s]),
                ]
                for s in SECTIONS
            ],
        )
    )
    add("")
    add(
        "Section boundaries are derived from content markers (annex covers, index "
        "headers, the capacity-annex title), never from hardcoded page numbers. "
        "The ranges above are the *result*, and are only a cross-check."
    )
    add("")
    add(
        "**Deviation from the agreed section list:** a `freight` section was added. "
        "PDF pages 1514-1673 are a separate KA barang book with its own index and "
        "page numbering; labelling them `krl` or `intercity` would have been wrong. "
        "This is a Phase 0 inventory field, not part of the AGENTS.md data contract."
    )
    add("")

    add("## 4. Type x section x subtype")
    add("")
    add(
        _table(
            ["Section", "Type", "Subtype", "Pages"],
            [[s, t, st, f"{n:,}"] for (s, t, st), n in sorted(by_subtype.items())],
        )
    )
    add("")

    add("## 5. Classifier rule hit counts")
    add("")
    add(
        _table(
            ["Rule", "Meaning", "Pages"],
            [[str(r), RULES[r], f"{by_rule.get(r, 0):,}"] for r in sorted(RULES)],
        )
    )
    add("")
    add(
        "Rules 4 and 5 (divider, annex cover) run before rules 6 and 7 because "
        'divider pages quote "Lintas Pelayanan" and "rangkaian" in their own '
        "notes. Without that order, divider pages were misread as summary tables "
        "and graphics (87 intercity pages alone)."
    )
    add("")

    add("## 6. Confidence")
    add("")
    add(
        _table(
            ["Level", "Meaning", "Pages"],
            [
                [
                    "high",
                    "matched a distinctive content marker (rules 1-5)",
                    f"{by_confidence.get('high', 0):,}",
                ],
                [
                    "medium",
                    "matched a structural or statistical heuristic (rules 6-9)",
                    f"{by_confidence.get('medium', 0):,}",
                ],
                [
                    "low",
                    "no rule matched, fell through to `unknown` (rule 10)",
                    f"{by_confidence.get('low', 0):,}",
                ],
            ],
        )
    )
    add("")
    add(
        "`high` means the marker is unambiguous, not that the page was checked. "
        "A human spot-check is still required."
    )
    add("")
    add("### 6.1 Confidence per rule")
    add("")
    rule_conf = summary["by_rule_and_confidence"]
    add(
        _table(
            ["Rule", "Meaning", "high", "medium", "low"],
            [
                [
                    str(r),
                    RULES[r],
                    f"{rule_conf.get(f'{r}:high', 0):,}",
                    f"{rule_conf.get(f'{r}:medium', 0):,}",
                    f"{rule_conf.get(f'{r}:low', 0):,}",
                ]
                for r in sorted(RULES)
            ],
        )
    )
    add("")
    below = summary["below_high_confidence_pages"]
    add(f"### 6.2 All {len(below)} pages below `high` confidence")
    add("")
    add(_ranges(below))
    add("")
    add(
        _table(
            ["PDF page", "Type", "Subtype", "Section", "Rule", "Confidence"],
            [
                [
                    str(n),
                    index[n]["type"],
                    index[n]["subtype"],
                    index[n]["section"],
                    str(index[n]["rule"]),
                    index[n]["confidence"],
                ]
                for n in below
            ],
        )
    )
    add("")
    add(
        "These are the pages a spot-check should start with: every one rests on a "
        "structural heuristic rather than a distinctive text marker."
    )
    add("")

    add("## 7. Does `time_density` separate the classes?")
    add("")
    add("`time_density` = clock-time tokens (`HH:MM` or `HH:MM:SS`) divided by word count.")
    add("")
    rows = []
    for t in PAGE_TYPES:
        values = [p["time_density"] for p in pages if p["type"] == t]
        if not values:
            rows.append([t, "0", "-", "-", "-"])
            continue
        rows.append(
            [
                t,
                f"{len(values):,}",
                f"{min(values):.3f}",
                f"{_median(values):.3f}",
                f"{max(values):.3f}",
            ]
        )
    add(_table(["Type", "Pages", "min", "median", "max"], rows))
    add("")
    add(
        "The separation is real but not clean: `train_table` and `line_table` both "
        "sit high, `graphic` sits at zero for the stringline and capacity charts, "
        "and `toc` overlaps `train_table`. That is why `time_density` is only used "
        "as a supporting signal (rule 2 continuation, rule 8), never as the sole "
        "reason for a label."
    )
    add("")

    add("## 8. Printed page <-> PDF page mapping")
    add("")
    add(
        "Printed page numbers were read from the page margin (a bare number alone "
        "on its own text line). The offset is `pdf_page - printed_page`."
    )
    add("")
    offset_rows = []
    for s in SECTIONS:
        section_pages = [p for p in pages if p["section"] == s]
        runs = _offset_runs(section_pages)
        if not runs:
            offset_rows.append([s, "-", "no stable numeric offset"])
            continue
        for start, end, offset in runs:
            offset_rows.append([s, f"{start}-{end}", f"+{offset}"])
    add(_table(["Section", "PDF range", "Offset"], offset_rows))
    add("")
    add("**The offset is not constant.** It changes at every book boundary:")
    add("")
    add("- PDF 58 — intercity book 1 starts at printed page 1 (offset +57)")
    add("- PDF 670 — intercity book 2 starts at printed page 1 (offset +669)")
    add("- PDF 834 — KRL book starts at printed page 1 (offset +833)")
    add("- PDF 1516 — freight book starts at printed page 1 (offset +1515)")
    add("- PDF 1826 — Lampiran IV starts at printed page 1 (offset +1825)")
    add("")
    add(
        "The stringline annex (PDF 7-51) does not use plain integers: it prints "
        "roman-prefixed numbers such as `II-2` and `VII-307`, and the extractor "
        "sometimes picks up chart axis labels instead. Treat stringline printed "
        "numbers as unreliable. The rolling-stock annex (PDF 1675-1824) mostly has "
        "no margin number at all."
    )
    add("")
    add("### 8.1 Boundary audit (page before / page after)")
    add("")
    add(
        "Every section change and every offset change, with the neighbour pages, so "
        "the boundary can be spot-checked by eye."
    )
    add("")
    boundary_rows = []
    seen: set[int] = set()

    def _add_boundary(before_index: int, change: str) -> None:
        before, after = pages[before_index - 1], pages[before_index]
        if after["page"] in seen:
            for row in boundary_rows:
                if row[5] == str(after["page"]):
                    row[10] = f"{row[10]}; {change}"
                    return
            return
        seen.add(after["page"])
        boundary_rows.append(
            [
                str(before["page"]),
                before["type"],
                before["subtype"],
                before["section"],
                before["confidence"],
                str(after["page"]),
                after["type"],
                after["subtype"],
                after["section"],
                after["confidence"],
                change,
            ]
        )

    # (a) section and book changes, page by page.
    for position in range(1, len(pages)):
        before, after = pages[position - 1], pages[position]
        reasons = []
        if before["section"] != after["section"]:
            reasons.append(f"section {before['section']} -> {after['section']}")
        if before.get("book") != after.get("book"):
            reasons.append(f"book {before.get('book')} -> {after.get('book')}")
        if reasons:
            _add_boundary(position, "; ".join(reasons))

    # (b) offset-run starts. Using runs, not per-page numbers, because the
    # stringline annex's per-page numbers are unreliable.
    for section in SECTIONS:
        for start, _end, offset in _offset_runs([p for p in pages if p["section"] == section]):
            position = start - 1
            if position >= 1:
                _add_boundary(position, f"printed offset starts +{offset}")

    boundary_rows.sort(key=lambda row: int(row[5]))
    add(
        _table(
            [
                "Before",
                "Type",
                "Subtype",
                "Section",
                "Conf.",
                "After",
                "Type",
                "Subtype",
                "Section",
                "Conf.",
                "Change",
            ],
            boundary_rows,
        )
    )
    add("")
    add(
        f"{len(boundary_rows)} boundaries. Offset changes are taken from stable "
        f"runs of at least {MIN_OFFSET_RUN} pages, so the unreliable per-page "
        "numbers in the stringline annex do not appear here."
    )
    add("")

    add("## 9. Twenty diverse sample pages")
    add("")
    sample_rows = []
    for page_no, reason in CURATED_SAMPLES:
        p = index.get(page_no)
        if p is None:
            continue
        sample_rows.append(
            [
                str(page_no),
                p["type"],
                p["subtype"],
                p["section"],
                f"{p['word_count']:,}",
                reason,
            ]
        )
    add(
        _table(
            ["PDF page", "Type", "Subtype", "Section", "Words", "Why it is representative"],
            sample_rows,
        )
    )
    add("")

    add("## 10. Seeded random sample (30 pages)")
    add("")
    add(f"Seed `{SAMPLE_SEED}`, uniform over all {total:,} pages. Use this to spot-check.")
    add("")
    rng = random.Random(SAMPLE_SEED)
    picked = sorted(rng.sample(range(1, total + 1), RANDOM_SAMPLE_SIZE))
    add(
        _table(
            ["PDF page", "Type", "Subtype", "Section", "Words", "Rule", "Confidence"],
            [
                [
                    str(n),
                    index[n]["type"],
                    index[n]["subtype"],
                    index[n]["section"],
                    f"{index[n]['word_count']:,}",
                    str(index[n]["rule"]),
                    index[n]["confidence"],
                ]
                for n in picked
            ],
        )
    )
    add("")

    add("## 11. Pages classified `unknown`")
    add("")
    unknown = summary["unknown_pages"]
    if unknown:
        add(f"{len(unknown)} page(s): {_ranges(unknown)}")
    else:
        add(
            "None. Every page matched a rule. This does **not** mean every label is "
            "correct — it means no page was left unlabelled."
        )
    add("")

    add("## 12. Train-table pages with no recognizable KA header")
    add("")
    no_header = [
        p["page"] for p in pages if p["type"] == "train_table" and p["train_header_count"] == 0
    ]
    add(
        f"{len(no_header):,} of {by_type.get('train_table', 0):,} train-table pages carry no "
        "`KA nnn (Name) Relasi` header. Most are continuation pages of a table that "
        "started on an earlier page; the KRL and freight books never use that header "
        "at all. Phase 1 must attach these pages to the preceding table."
    )
    add("")
    add(f"Pages: {_ranges(no_header)}")
    add("")

    add("## 13. Heuristics used")
    add("")
    add(
        _table(
            ["Rule", "Condition", "Type"],
            [
                ["1", "0 words, or <=25 words with no clock times", "`other`"],
                [
                    "2",
                    "`DAFTAR ISI`, or `URUT KA`+`BRK`+`DAT`, "
                    "or >=3 class keywords with time density >=0.1",
                    "`toc`",
                ],
                ["3", "`STASIUN DAN PERHENTIAN`", "`train_table`"],
                ["4", "`DAFTAR WAKTU` + `ISI:`", "`other` (section divider)"],
                [
                    "5",
                    "`LAMPIRAN` + `KEPUTUSAN DIREKTUR JENDERAL` and <100 words",
                    "`other` (cover)",
                ],
                ["6", "`URUT KERETA API` or `LINTAS PELAYANAN`", "`line_table`"],
                [
                    "7",
                    "`GRAFIK PERJALANAN`, `GAMBAR GRAFIS`, `RANGKAIAN`, `SIAP GUNA`, "
                    "`KAPASITAS LINTAS`, `DUDUK BERDIRI`, `TS UNIT`, `JALUR GANDA`, `EFF OPS`",
                    "`graphic`",
                ],
                ["8", "landscape or oversized, 0 clock times, >50 words", "`graphic`"],
                ["9", "`UNTUK LINTAS` or `KETERANGAN` and <300 words", "`legend`"],
                ["10", "nothing matched", "`unknown`"],
            ],
        )
    )
    add("")
    add(
        "`table_count` is recorded per page as `table_header_count` (occurrences of "
        "`Stasiun dan Perhentian`). "
        f"{len(summary['multi_table_pages']):,} pages carry two or more, so Phase 1 "
        "must split multi-table pages before parsing."
    )
    add("")

    add("## 14. Risks and anomalies")
    add("")
    add(
        "1. **Text-stream order is unreliable.** On KRL pages the stream emits "
        "`Berangkat` before `Datang` (PDF 1001: x=268 -> 11:54, x=314 -> 11:55). "
        "Rows and columns must be rebuilt from x/y coordinates. This is now Hard Rule 11."
    )
    add(
        "2. **Two trains per page.** "
        f"{len(summary['multi_table_pages']):,} of {by_type.get('train_table', 0):,} "
        "train-table pages contain two or more table headers. A one-table-per-page "
        "parser will silently drop half the data."
    )
    add(
        "3. **Printed page numbers restart per book.** Five boundaries, listed in "
        "section 8. Any code that assumes a single offset will mis-map pages."
    )
    add(
        "4. **12 image-only pages** (1-5, 1676, 1702, 1707, 1740, 1776, 1813, 1819). "
        "None contain timetable data; no OCR is planned."
    )
    add(
        "5. **Inline footnotes** such as `= ka 46 (ka 46 //)` and `// ka 5014 (ka 5014 =)` "
        "sit inside the row stream and will corrupt a naive row split."
    )
    add(
        "6. **`Ls` and `-` are not times.** `Ls` in Keterangan means pass-through; "
        "`-` means an empty cell. Both must become `null`/`pass`, never a time."
    )
    add(
        "7. **Header count != train count.** 636 `Relasi` headers cover 319 distinct "
        "train numbers; KRL and freight tables have no such header."
    )
    add(
        "8. **The stringline annex is not machine-readable.** It is a chart, not a "
        "table. It is classified for completeness and must not be parsed."
    )
    add(
        "9. **`legend` is empty.** The chart legend lives on PDF page 51 inside a "
        "stringline page. If a later Gapeka prints it separately, rule 9 will catch it."
    )
    add(
        "10. **Section boundaries are marker-based.** If the Gapeka format changes, "
        "the markers in `pipeline/classify.py` must be re-verified before trusting "
        "the section field."
    )
    add("")

    add("## 15. The intercity section is two books")
    add("")
    add(
        "PDF 52-811 is **not** one book. The section contains two books with "
        "independent printed numbering, and inside them each train series opens "
        "with its own divider:"
    )
    add("")
    book_rows = []
    for book_number in sorted({p["book"] for p in pages if p["section"] == "intercity"}):
        members = [p for p in pages if p["section"] == "intercity" and p["book"] == book_number]
        tables = [p for p in members if p["type"] == "train_table"]
        subtypes = sorted({p["subtype"] for p in tables})
        book_rows.append(
            [
                str(book_number),
                _ranges([p["page"] for p in members]),
                f"{len(tables):,}",
                ", ".join(f"`{s}`" for s in subtypes) or "-",
            ]
        )
    add(_table(["Book", "PDF range", "train_table pages", "table subtypes"], book_rows))
    add("")
    add(
        "**Book 1 (PDF 58-664)** opens with `KA 1 (Anggrek) Relasi SBI - GMR`: "
        "long-distance intercity services. Printed page 1 is PDF 58, offset +57."
    )
    add("")
    add(
        "**Book 2 (PDF 670-811)** opens with `KA 351 (Siliwangi) Lintas Pelayanan "
        "CPT - SI`: local and commuter-class regional services. Printed page 1 is "
        "PDF 670, offset +669. Note that book 2's divider uses `Lintas Pelayanan` "
        "rather than `Relasi`, which is why the train-table header pattern that "
        "works in book 1 finds nothing in book 2."
    )
    add("")
    add(
        "**Inside both books** each train *series* also opens with its own "
        "`DAFTAR WAKTU ... ISI:` divider (135 of them). Those dividers do **not** "
        "reset numbering, so they start a new series, not a new book. The "
        "`book` field therefore counts only numbering resets."
    )
    add("")
    add(
        "Consequences for Phase 1: the index parser must handle `Relasi` (book 1) "
        "and `Lintas Pelayanan` (book 2) separately, and the offset table must be "
        "keyed per book rather than per section."
    )
    add("")

    add("## 16. Train counts per section and per pattern")
    add("")
    add(
        "No pattern is authoritative. The index pages are the primary authority for "
        "which trains exist; `Relasi` headers and summary tables are cross-checks. "
        "Counts are reported per section because the three sections use different "
        "header formats."
    )
    add("")
    numbers = summary["train_numbers"]["by_section"]
    per_section_rows = []
    for section in SECTIONS:
        kinds = numbers.get(section)
        if not kinds or not kinds["union_distinct"]:
            continue
        per_section_rows.append(
            [
                section,
                f"{kinds['index_distinct']:,}",
                f"{kinds['relasi_distinct']:,}",
                f"{kinds['lintas_distinct']:,}",
                f"{kinds['union_distinct']:,}",
            ]
        )
    add(
        _table(
            ["Section", "index", "Relasi headers", "Lintas Pelayanan", "union"],
            per_section_rows,
        )
    )
    add("")
    add(
        "`index` = distinct train numbers matched by the index row pattern "
        "(`seq  train_no  CLASS  name  relation  depart  arrive  page`). `Relasi` "
        "and `Lintas Pelayanan` = distinct numbers on pages of that type. `union` "
        "= the three combined."
    )
    add("")
    add("Where they disagree:")
    add("")
