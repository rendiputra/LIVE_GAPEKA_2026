"""Generate docs/phase5_report.md from the engine artefacts.

Usage:
    python -m pipeline.phase5_report
"""

from __future__ import annotations

import json
from pathlib import Path

DOCS = Path("docs")
REVIEW = Path("data/review")


def load(path: Path, default):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else default


def render(sweep: dict, replay_trips: list[dict], golden_count: int) -> str:
    lines: list[str] = []
    add = lines.append

    add("# Phase 5 — Position engine")
    add("")
    add("> Generated by `python -m pipeline.phase5_report`. Do not edit by hand.")
    add("> Nothing here is described as *verified*; see `docs/verification_status.md`.")
    add("")

    add("## Phase 5b (follow-up)")
    add("")
    add(
        "Phase 5b applied the H6 SRI override (which unblocks KA 249/250), corrected the "
        "inverted turn-back rule, added the human segment-review mechanism (ADR 005) and "
        "rebuilt the replay on a 30-hour window. Full detail and before/after tables: "
        "`docs/phase5b_report.md`."
    )
    add("")
    b5 = load(REVIEW / "t1_5b_after.json", {})
    if b5:
        add(f"- trips loaded by the engine: **{b5.get('trips_loaded_by_engine')}**")
        add(f"- trips shown by default: **{b5.get('shown_by_default')}**")
        add(f"- geometry content hash: `{b5.get('segments_hash')}`")
        add("")

    add("## What the engine is")
    add("")
    add(
        "A pure function: `positions_at(snapshot, instant, policy) -> [TrainPosition]`. "
        "No database, no network, no system clock, no randomness inside the core. "
        "Motion model `trapezoid_v1` (ADR 004). Every position carries `estimated = true`."
    )
    add("")

    add("## Snapshot")
    add("")
    snapshot = sweep.get("snapshot", {})
    add(f"- version: **{snapshot.get('version_name')}** (id {snapshot.get('version_id')})")
    add(
        f"- effective_from: `{snapshot.get('effective_from')}`, "
        f"effective_to: `{snapshot.get('effective_to')}`"
    )
    add(f"- trips loaded: **{snapshot.get('trips')}**")
    add(f"- max day_offset: **{snapshot.get('max_day_offset')}**")
    add(f"- geometry content hash: `{snapshot.get('content_hash')}`")
    add("")

    add("## 24-hour sweep (2026-12-01, 60 s step)")
    add("")
    add("| Metric | Value |")
    add("|---|---|")
    add(f"| samples | {sweep['active']['samples']} |")
    add(f"| active trips, peak | **{sweep['active']['peak']}** |")
    add(f"| active trips, median | **{sweep['active']['median']}** |")
    add(f"| positions off-polyline (> 1 m) | **{sweep['off_polyline_positions']}** |")
    add(f"| continuity violations | **{sweep['continuity_violations']}** |")
    add(f"| continuity samples skipped (ambiguous) | {sweep['continuity_ambiguous_skipped']} |")
    legs = sweep["legs"]
    add(f"| timed legs | {legs['total']} |")
    add(
        f"| legs with cruise > printed max +10% | "
        f"**{legs['over_printed_max_10pct']}** of {legs['with_printed_max']} |"
    )
    add("")

    add("### Cruise speed vs the printed maximum")
    add("")
    add(
        "Each timed leg's cruise speed is compared with the PDF's `Kecepatan Maksimum` "
        "on the departing row (falling back to the arriving row when the departing "
        "value is `0` or `-`). The PDF does not state which stretch a printed value "
        "covers, so this is evidence, not a gate (V13)."
    )
    add("")
    add("| cruise / printed | legs |")
    add("|---|---|")
    for bucket, count in legs["cruise_to_printed_ratio_buckets"].items():
        add(f"| {bucket} | {count} |")
    add("")
    if sweep.get("fast_leg_examples"):
        add("Legs above the printed maximum by more than 10%:")
        add("")
        add("| trip | from -> to | cruise km/h | printed max | ratio |")
        add("|---|---|---|---|---|")
        for row in sweep["fast_leg_examples"]:
            add(
                f"| `{row['trip_id']}` | {row['from']} -> {row['to']} | "
                f"{row['cruise_kmh']} | {row['printed_max_kmh']} | {row['ratio']} |"
            )
        add("")

    add("## Benchmark")
    add("")
    bench = sweep["benchmark_ms"]
    add(
        f"`positions_at` over all active trips: median **{bench['median']} ms**, "
        f"p95 **{bench['p95']} ms**, max **{bench['max']} ms** ({bench['runs']} runs). "
        "Target was < 50 ms."
    )
    add("")

    add("## Trips excluded, by reason")
    add("")
    add(
        f"Of **{sweep.get('trips_total')}** trips in the database, "
        f"**{sweep.get('trips_shown_by_default')}** are shown under the default policy. "
        "These counts read the database, not the snapshot (the snapshot has already "
        "dropped `has_unmeasured` trips, so counting from it would hide them)."
    )
    add("")
    add("| Reason | Trips |")
    add("|---|---|")
    for reason, count in sorted(sweep["excluded"].items()):
        add(f"| `{reason}` | {count} |")
    add("")

    add("## Replay page")
    add("")
    add(
        "`data/review/engine_replay.html` — 30 s frames for 2026-12-01, with a time "
        "slider, play/pause, speed control, per-train labels (status, from/to, next "
        "stop and its printed time) and a printed-vs-engine table."
    )
    add("")
    add("| KA | geometry status | service class | coarser estimate |")
    add("|---|---|---|---|")
    for trip in replay_trips:
        add(
            f"| {trip['train_no']} | {trip['status']} | {trip['class']} | "
            f"{'yes' if trip['coarse'] else 'no'} |"
        )
    add("")

    add("## Golden frames")
    add("")
    add(
        f"`engine/golden_frames.json` holds **{golden_count}** sampled frames for "
        "browser-port parity tests. They are **not** human-verified."
    )
    add("")

    add("## Limitations")
    add("")
    for item in [
        "The motion model is an assumption, not timetable data (ADR 004).",
        "`daily` for reguler trains is assumed; the PDF states no weekday pattern (ADR 002).",
        "Fakultatif and unknown-class trips are hidden by default.",
        "Trips with `has_unmeasured` geometry are never shown.",
        "KA 249/250 are not loaded because SRI snaps 1,806 m from rail (> 1,000 m limit), "
        "so they are absent from the replay page; the page states this rather than "
        "substituting a different train silently.",
        f"{sweep['legs']['over_printed_max_10pct']} of {sweep['legs']['with_printed_max']} "
        "legs imply a cruise speed more than 10% above the printed maximum. They are "
        "reported as V13 evidence and left uncorrected.",
        "The replay's reproduction check is CIRCULAR: the engine is built from the same "
        "printed times, so agreement only shows the loader, cumulative distances and "
        "motion profile are mutually consistent. It is not independent validation.",
        "12 `stop_times` rows arrive before midnight and depart after it; one `day_offset` "
        "per row cannot represent that, so those arrivals are a day late. Reported, not "
        "patched (see `docs/phase5b_report.md`).",
        "No position has been checked against reality; this is a schedule estimate only.",
    ]:
        add(f"- {item}")
    add("")

    return "\n".join(lines) + "\n"


def main() -> int:
    sweep = load(REVIEW / "r1_engine_sweep.json", {})
    if not sweep:
        print("run `python -m pipeline.engine_sweep` first")
        return 2

    # Rebuild the trip list the replay page used, from the page payload.
    replay_trips = []
    page = REVIEW / "engine_replay.html"
    if page.exists():
        import re

        text = page.read_text(encoding="utf-8")
        match = re.search(r"const DATA = (\{.*?\});", text, re.S)
        if match:
            replay_trips = json.loads(match.group(1)).get("trips", [])

    golden = Path("engine/golden_frames.json")
    # The file is a dict with metadata AND a "frames" list; count the frames,
    # never the top-level keys.
    golden_count = 0
    if golden.exists():
        payload = json.loads(golden.read_text(encoding="utf-8"))
        golden_count = len(payload.get("frames", [])) if isinstance(payload, dict) else len(payload)

    DOCS.mkdir(parents=True, exist_ok=True)
    (DOCS / "phase5_report.md").write_text(
        render(sweep, replay_trips, golden_count), encoding="utf-8"
    )
    print(f"wrote {DOCS / 'phase5_report.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
