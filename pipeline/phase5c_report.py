"""Phase 5c report: pins, reviews, day offsets, coverage, experiment.

Every number is read from a generated file:

- ``data/review/t1_5b_after.json`` (before this round)
- ``data/review/t1_5c_after.json`` (after this round)
- ``data/review/bridge_probe.json``
- ``data/review/snap_experiment.json``
- ``data/review/day_offset_correction.json``
- ``data/review/coverage_blockers.json``
- ``data/review/r1_engine_sweep.json``

Usage:
    python -m pipeline.phase5c_report
"""

from __future__ import annotations

import json
from pathlib import Path

REVIEW = Path("data/review")
DOCS = Path("docs")


def load(path: Path, default=None):
    if not path.exists():
        return default
    return json.loads(path.read_text(encoding="utf-8"))


def table(add, title: str, before: dict, after: dict, label: str) -> None:
    add(f"## {title}")
    add("")
    add(f"| {label} | Before | After |")
    add("|---|---|---|")
    for key in sorted(set(before) | set(after)):
        add(f"| `{key}` | {before.get(key, 0)} | {after.get(key, 0)} |")
    add(f"| **total** | {sum(before.values())} | {sum(after.values())} |")
    add("")


def main() -> int:
    before = load(REVIEW / "t1_5b_after.json")
    after = load(REVIEW / "t1_5c_after.json")
    bridge = load(REVIEW / "bridge_probe.json", {})
    experiment = load(REVIEW / "snap_experiment.json", {})
    offsets = load(REVIEW / "day_offset_correction.json", {})
    coverage = load(REVIEW / "coverage_blockers.json", {})
    sweep = load(REVIEW / "r1_engine_sweep.json", {})

    if not before or not after:
        print("missing t1_5b_after.json / t1_5c_after.json")
        return 2

    lines: list[str] = []
    add = lines.append

    add("# Phase 5c — pins, segment reviews, day offsets")
    add("")
    add("> Generated by `python -m pipeline.phase5c_report`. Do not edit by hand.")
    add("> Nothing here is described as *verified*; see `docs/verification_status.md`.")
    add("")

    add("## What changed")
    add("")
    for item in [
        "**Snap pins (Q1a)**: `data/config/snap_pins.yaml` pins TLM to way 1311188691 "
        "and BTT to way 163741924. BTT-CS is now 4.953 km instead of 11.544 km.",
        "**TLM (Q2)**: the H5 coordinate is applied together with its pin.",
        "**Segment reviews (Q4)**: eight suspect segments are `accept_route`, so they "
        "become `osm_routed_reviewed` and count as complete. BTT-CS is not among them.",
        "**Day offsets (Q3)**: `arrive_day_offset` / `depart_day_offset` split a stop "
        "that straddles midnight.",
        "**P1**: SRI is `override_rule_approved`, not a human choice.",
        "**P2**: `data/config/*.yaml` is tracked and its hash is in the build.",
        "**P3**: one shared definition of segment usage (`pipeline/trip_pairs.py`).",
        "**P4**: the 1.69 m bridge candidate changes nothing and stays unapplied.",
    ]:
        add(f"- {item}")
    add("")

    table(
        add,
        "Station coordinate status",
        before["coord_status"],
        after["coord_status"],
        "coord_status",
    )
    table(add, "Segment quality", before["segment_quality"], after["segment_quality"], "quality")
    table(add, "Trip geometry status", before["trip_status"], after["trip_status"], "status")
    table(
        add,
        "Trips blocked by has_unmeasured, per book",
        before["blocked"],
        after["blocked"],
        "book",
    )

    add("## Headline counts")
    add("")
    add("| Metric | Before | After |")
    add("|---|---|---|")
    add(
        f"| trips shown by default | {before.get('shown_by_default')} | "
        f"**{after['shown_by_default']}** |"
    )
    add(
        f"| trips loaded by the engine | {before.get('trips_loaded_by_engine')} | "
        f"**{after['trips_loaded_by_engine']}** |"
    )
    add(
        f"| bypassed waypoint rows | {before.get('bypass_rows')} | **{after.get('bypass_rows')}** |"
    )
    add(
        f"| day offsets derived | {before.get('day_offset_derived_rows', 0)} | "
        f"**{after.get('day_offset_derived_rows')}** |"
    )
    add("")

    add("## Coordinate provenance (P1)")
    add("")
    add("| Provenance | Stations |")
    add("|---|---|")
    for key, value in sorted(after["coord_provenance"].items()):
        add(f"| `{key}` | {value} |")
    add("")
    add(
        "`override_rule_approved` is a rule, not a person: the coordinate came from "
        "rule H6 (one exact OSM name match, gate passed), not from a human choosing a "
        "point. It is listed separately for that reason."
    )
    add("")

    add("## Snap pins (Q1a)")
    add("")
    add("| Station | Way | Snap (m) | Decided by |")
    add("|---|---|---|---|")
    for code, row in sorted(after.get("snap_pins_applied", {}).items()):
        add(f"| `{code}` | {row['way_id']} | {row['snap_distance_m']} | {row['decided_by']} |")
    add("")
    add(f"Unusable pins: **{len(after.get('snap_pins_unusable', []))}**.")
    add("")

    add("## Content hashes")
    add("")
    add("| Artefact | Before | After |")
    add("|---|---|---|")
    add(f"| segments | `{before.get('segments_hash')}` | `{after['segments_hash']}` |")
    add(f"| database | `{before.get('db_hash')}` | `{after['db_hash']}` |")
    add(f"| config (tracked) | `{before.get('config_hash', 'n/a')}` | `{after['config_hash']}` |")
    add("")

    if offsets:
        add("## Midnight-straddling rows (Q3)")
        add("")
        add(f"**{offsets['affected_count']}** rows arrive on the previous day.")
        add("")
        add("| Trip | seq | Station | Arrive | Depart | Dwell (min) |")
        add("|---|---|---|---|---|---|")
        for row in offsets["affected"]:
            add(
                f"| `{row['trip_id']}` | {row['seq']} | `{row['station_code']}` | "
                f"{row['arrive']} | {row['depart']} | {row['dwell_minutes']} |"
            )
        add("")
        add(
            f"Long dwells over {offsets['long_dwell_threshold_minutes']} min: "
            f"**{len(offsets['long_dwells'])}**."
        )
        add("")

    if bridge:
        add("## Bridge probe (P4)")
        add("")
        add("| Candidate | Segment | Straight km | Without | With | Delta km |")
        add("|---|---|---|---|---|---|")
        for row in bridge["rows"]:
            add(
                f"| {row['candidate']} | {row['segment']} | {row['straight_km']} | "
                f"{row['routed_without_km']} | {row['routed_with_km']} | {row['delta_km']} |"
            )
        add("")
        add(
            "Every delta is zero: the components are not on any shortest path once "
            "the pins choose the right track. Nothing is applied."
        )
        add("")

    if experiment:
        add("## Routing-aware snapping experiment (Q1b)")
        add("")
        add(f"- stations evaluated: **{experiment['stations_evaluated']}**")
        add(f"- stations changed: **{experiment['stations_changed']}**")
        add(f"- changes reverted by the guard: **{len(experiment['changes_reverted_by_guard'])}**")
        add(f"- segments changed by more than 0.5 %: **{len(experiment['segments_changed'])}**")
        add(f"- segments made longer: **{len(experiment['segments_longer'])}**")
        add(
            f"- total routed length: {experiment['total_length_before_km']} km -> "
            f"{experiment['total_length_after_km']} km"
        )
        add("")
        add("| Segment | Before km | After km | Delta % |")
        add("|---|---|---|---|")
        for row in experiment["segments_changed"]:
            add(
                f"| {row['segment']} | {row['before_km']} | {row['after_km']} | "
                f"{row['delta_pct']} |"
            )
        add("")
        add("Pilot trips (must stay within 0.5 %):")
        add("")
        add("| KA | Before km | After km | Delta % | Within 0.5 % |")
        add("|---|---|---|---|---|")
        for number, row in experiment["pilot_trips"].items():
            if not row.get("found"):
                add(f"| {number} | - | - | - | not found |")
                continue
            add(
                f"| {number} | {row['before_km']} | {row['after_km']} | "
                f"{row['delta_pct']} | {'yes' if row['within_0_5pct'] else 'NO'} |"
            )
        add("")
        add("Pins reproduced by the optimiser:")
        add("")
        for code, row in experiment["pins_reproduced"].items():
            add(
                f"- `{code}`: pinned way {row['pinned_way']}, chosen "
                f"{row['chosen_way']} -> {'reproduced' if row['reproduced'] else 'NOT reproduced'}"
            )
        add("")
        add(
            "The experiment is **not** the default (ADR 006). Without the guard it made "
            "four segments longer, including both pinned ones."
        )
        add("")

    if sweep:
        add("## Sweep (2026-12-01)")
        add("")
        add("| Metric | Value |")
        add("|---|---|")
        add(f"| active trips, peak | {sweep['active']['peak']} |")
        add(f"| active trips, median | {sweep['active']['median']} |")
        add(f"| active 00:00-05:00, peak | {sweep['active_00_05']['peak']} |")
        add(f"| active 00:00-05:00, median | {sweep['active_00_05']['median']} |")
        add(f"| positions off-polyline | {sweep['off_polyline_positions']} |")
        add(f"| continuity violations | {sweep['continuity_violations']} |")
        add(
            f"| legs over printed max +10% | "
            f"{sweep['legs']['over_printed_max_10pct']} of "
            f"{sweep['legs']['with_printed_max']} |"
        )
        add(f"| benchmark median ms | {sweep['benchmark_ms']['median']} |")
        add("")

    if coverage:
        add("## Coverage (T4)")
        add("")
        add(
            f"**{coverage['shown_by_default']}** of **{coverage['total_trips']}** "
            "trips are shown by default."
        )
        add("")
        add("| Reason | Trips |")
        add("|---|---|")
        for reason, counts in coverage["hidden_by_reason"].items():
            add(f"| `{reason}` | {sum(counts.values())} |")
        add("")
        add("Top blockers by greedy marginal gain:")
        add("")
        add("| Unblocks | Touches | Blocker |")
        add("|---|---|---|")
        for row in coverage["top_blockers"][:20]:
            add(f"| {row['marginal_unblocked']} | {row['trips_touching']} | {row['label']} |")
        add("")
        add("Twenty services still never shown:")
        add("")
        add("| KA | Name | Book | Reason | Blockers |")
        add("|---|---|---|---|---|")
        for row in coverage["never_shown"][:20]:
            add(
                f"| {row['train_no']} | {row['name'] or ''} | {row['book']} | "
                f"{row['reason']} | {'; '.join(row['blockers']) or '-'} |"
            )
        add("")

    DOCS.mkdir(parents=True, exist_ok=True)
    target = DOCS / "phase5c_report.md"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
