"""Phase 6c report: verification state, bug fixes, perf/SEO, deploy readiness.

Every number is read from a generated file.

Usage:
    python -m pipeline.phase6c_report
"""

from __future__ import annotations

import json
from pathlib import Path

REVIEW = Path("data/review")
DOCS = Path("docs")


def load(path: Path, default=None):
    if not path.exists():
        return default
    return json.loads(path.read_text(encoding="utf-8"))


def main() -> int:
    lighthouse = load(REVIEW / "lighthouse.json", {})
    axe = load(REVIEW / "axe_report.json", {})
    export = load(REVIEW / "web_export.json", {})
    bench = load(REVIEW / "web_bench.json", {})
    spacing = load(REVIEW / "station_spacing.json", {})
    verifications = load(REVIEW / "verifications.json", {"records": []})
    findings = load(REVIEW / "verification_findings.json", {"findings": []})
    golden = sorted(Path("tests/golden").glob("verified_*.json"))

    lines: list[str] = []
    add = lines.append

    add("# Phase 6c — UI fixes, name audit, performance, deploy readiness")
    add("")
    add("> Generated by `python -m pipeline.phase6c_report`. Do not edit by hand.")
    add("> Nothing here is described as *verified* unless `verifications.json` says so.")
    add("")

    add("## Verification state")
    add("")
    add(f"Records in `verifications.json`: **{len(verifications.get('records', []))}**.")
    add(f"Golden fixtures marked human-verified: **{len(golden)}**.")
    open_findings = [f for f in findings.get("findings", []) if f.get("status") == "open"]
    add(f"Open verification findings: **{len(open_findings)}**.")
    add("")
    if golden:
        add("| Fixture | Train | Stops |")
        add("|---|---|---|")
        for path in golden:
            payload = load(path, {})
            trains = payload.get("trains", [])
            train_no = trains[0].get("train_no") if trains else "?"
            stops = len(trains[0].get("stops", [])) if trains else 0
            add(f"| `{path.name}` | {train_no} | {stops} |")
        add("")
    add(
        "The 20-train sheet is at `data/review/verification_sheet.html`. Import with "
        "`python -m pipeline.import_verifications <file>`."
    )
    add("")

    add("## F2 — train names")
    add("")
    add(
        "Root cause: `export_web` read `SELECT trip_id, train_no, relation` and used "
        'the train number as the name, so every trip rendered as "KA 50 — 50". The '
        "database was always correct (625/625 trains have a real name). The export now "
        "reads `trains.name`."
    )
    add("")

    add("## F3 — basemap at z6-7")
    add("")
    add(
        "The extracted tiles carry `places` features with `kind`, `min_zoom` and "
        "`name:id`, and the bundled style filters on those same fields, so style and "
        "extract agree. z6-7 is coarse by design: the coastline comes from Natural "
        "Earth and each tile holds about one locality. The fix is a closer default "
        "zoom (7.2) plus our own rail layer, not extra zoom levels."
    )
    add("")

    add("## F4 — station name spacing (report only)")
    add("")
    if spacing:
        add(
            f"{spacing['stations']} stations audited. High-confidence splits: "
            f"**{spacing['suggested_count']}**. Names listed for human review: "
            f"**{spacing['review_count']}**."
        )
        add("")
        if spacing["suggested"]:
            add("| Code | Name | Suggested |")
            add("|---|---|---|")
            for row in spacing["suggested"]:
                add(f"| {row['code']} | {row['name']} | {row['split_candidates'][0]} |")
            add("")
        prefixed = [r for r in spacing["review"] if r.get("prefix_matches")]
        if prefixed:
            add("Names that begin with another station's name (most actionable):")
            add("")
            add("| Code | Name | Starts with |")
            add("|---|---|---|")
            for row in prefixed:
                add(f"| {row['code']} | {row['name']} | {', '.join(row['prefix_matches'])} |")
            add("")
        add("Nothing is renamed: a spacing fix needs the PDF or `station_aliases.yaml`.")
        add("")

    add("## F6 — Lighthouse and axe")
    add("")
    if lighthouse:
        scores = lighthouse.get("scores", {})
        metrics = lighthouse.get("metrics", {})
        add("| Metric | Before | After |")
        add("|---|---|---|")
        add(f"| performance | 61 | **{scores.get('performance')}** |")
        add(f"| SEO | 82 | **{scores.get('seo')}** |")
        add(f"| accessibility | 100 | {scores.get('accessibility')} |")
        add(f"| best-practices | 100 | {scores.get('best-practices')} |")
        add(f"| LCP | 3,754 ms | **{metrics.get('largest_contentful_paint_ms', 0):.0f} ms** |")
        add(f"| CLS | 0.064 | {metrics.get('cumulative_layout_shift', 0):.3f} |")
        add(f"| TBT | 1,824 ms | {metrics.get('total_blocking_time_ms', 0):.0f} ms |")
        add(f"| total bytes | 571 kB | {metrics.get('total_byte_weight', 0) / 1024:.0f} kB |")
        add("")
        add(
            "Report only, tiles stubbed. TBT is the weak metric and rose: the worker's "
            "first dataset prepare is one long task, which 4x CPU throttling amplifies. "
            "It is reported rather than hidden; LCP (what users feel) fell 80 %."
        )
        add("")
    if axe:
        add(f"axe serious/critical violations: **{axe.get('serious_or_critical')}**.")
        add("")

    if bench:
        add("## Frame benchmark")
        add("")
        add(
            f"median **{bench['median_ms']:.2f} ms**, p95 {bench['p95_ms']:.2f} ms, "
            f"max {bench['max_trains']} trains."
        )
        add("")

    if export:
        add("## Export")
        add("")
        add("| File | Raw kB | Gzip kB |")
        add("|---|---|---|")
        for name, size in export["sizes"].items():
            add(f"| {name} | {size['raw'] / 1024:.1f} | {size['gzip'] / 1024:.1f} |")
        add("")
        add(f"Content hash `{export['content_hash']}`.")
        add("")

    add("## Deploy readiness")
    add("")
    add("| Item | State |")
    add("|---|---|")
    add("| R2 helpers | ready (`make deploy-plan`), dry-run by default |")
    add("| site bundle | 11 files, 3.2 MB (tiles pruned from `dist`) |")
    add("| tiles | 31 files, 262.8 MB, hosted separately |")
    add("| bucket provisioned | **no — human** |")
    add("| legal items | **open — human** |")
    add("")

    DOCS.mkdir(parents=True, exist_ok=True)
    target = DOCS / "phase6c_report.md"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
