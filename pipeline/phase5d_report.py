"""Phase 5d report: H8-H11, the review page, the replay fixes.

Every number comes from a generated file:
``t1_5c_after.json`` (before), ``t1_5d_after.json`` (after),
``h8_h11_gate.json``, ``r1_engine_sweep.json``, ``coverage_blockers.json``.

Usage:
    python -m pipeline.phase5d_report
"""

from __future__ import annotations

import json
from pathlib import Path

REVIEW = Path("data/review")
DOCS = Path("docs")


def load(path: Path, default=None):
    if not path.exists():
        return default
    return json.loads(path.read_text(encoding="utf-8"))


def table(add, title: str, before: dict, after: dict, label: str) -> None:
    add(f"## {title}")
    add("")
    add(f"| {label} | Before | After |")
    add("|---|---|---|")
    for key in sorted(set(before) | set(after)):
        add(f"| `{key}` | {before.get(key, 0)} | {after.get(key, 0)} |")
    add(f"| **total** | {sum(before.values())} | {sum(after.values())} |")
    add("")


def main() -> int:
    before = load(REVIEW / "t1_5c_after.json")
    after = load(REVIEW / "t1_5d_after.json")
    gate = load(REVIEW / "h8_h11_gate.json", {})
    sweep = load(REVIEW / "r1_engine_sweep.json", {})
    coverage = load(REVIEW / "coverage_blockers.json", {})

    if not before or not after:
        print("missing t1_5c_after.json / t1_5d_after.json")
        return 2

    lines: list[str] = []
    add = lines.append

    add("# Phase 5d — H8-H11 and the review/replay fixes")
    add("")
    add("> Generated by `python -m pipeline.phase5d_report`. Do not edit by hand.")
    add("> Nothing here is described as *verified* except what `verifications.json` records.")
    add("")

    add("## What changed")
    add("")
    for item in [
        "**H8**: KRAI (Karangsari, Garut) and KRR (Karangsari, Banyumas) are recorded "
        "as distinct stations with a disambiguator, and the name conflict is marked "
        "resolved by a human in the evidence report.",
        "**H9**: the human validated OSM node/1244940845 for SRI on the map. It is "
        "recorded in `verifications.json` and `stations.human_confirmed = 1`; the "
        "provenance stays `override_rule_approved`.",
        "**H10**: RO (Rejoso, Pasuruan) is a distinct station. Applied by rule H10 "
        "(single exact OSM match, snap 1.0 m, triple PS-RO-GI 1.000).",
        "**H11**: KDB (Kedungbanteng) had a Wikidata coordinate 5,208 m from rail. "
        "Applied by rule H11 (snap 1.4 m, triple WK-KDB-KRO 1.019). This unblocked "
        "the KDB-KRO and KDB-WK pairs.",
        "**A2**: the review page lists human-decided segments in their own table.",
        "**A3**: the replay gained a trip dropdown, a follow toggle and an active-train "
        "list; its selection notes no longer claim a status.",
        "**A4**: routing-aware snapping stays an experiment (ADR 006 addendum).",
    ]:
        add(f"- {item}")
    add("")

    table(
        add,
        "Station coordinate status",
        before["coord_status"],
        after["coord_status"],
        "coord_status",
    )
    table(add, "Segment quality", before["segment_quality"], after["segment_quality"], "quality")
    table(add, "Trip geometry status", before["trip_status"], after["trip_status"], "status")
    table(
        add,
        "Trips blocked by has_unmeasured, per book",
        before["blocked"],
        after["blocked"],
        "book",
    )

    add("## Headline counts")
    add("")
    add("| Metric | Before | After |")
    add("|---|---|---|")
    add(
        f"| trips shown by default | {before['shown_by_default']} | "
        f"**{after['shown_by_default']}** |"
    )
    add(
        f"| trips loaded by the engine | {before['trips_loaded_by_engine']} | "
        f"**{after['trips_loaded_by_engine']}** |"
    )
    add(f"| bypassed waypoint rows | {before['bypass_rows']} | {after['bypass_rows']} |")
    add(
        f"| human-confirmed coordinates | {before.get('human_confirmed', 0)} | "
        f"**{after['human_confirmed']}** |"
    )
    add("")

    add("## Coordinate provenance")
    add("")
    add("| Provenance | Stations |")
    add("|---|---|")
    for key, value in sorted(after["coord_provenance"].items()):
        add(f"| `{key}` | {value} |")
    add("")
    add("Rule-approved coordinates (not human choices):")
    add("")
    if gate:
        add("| Code | Rule | Snap (m) | Triple ratio |")
        add("|---|---|---|---|")
        for row in gate.get("results", []):
            if row.get("outcome") != "applied":
                continue
            add(
                f"| `{row['code']}` | {row.get('rule', '')} | "
                f"{row.get('snap_m')} | {row.get('ratio')} |"
            )
        add("")

    add("## Content hashes")
    add("")
    add("| Artefact | Before | After |")
    add("|---|---|---|")
    add(f"| segments | `{before['segments_hash']}` | `{after['segments_hash']}` |")
    add(f"| database | `{before['db_hash']}` | `{after['db_hash']}` |")
    add(f"| config | `{before['config_hash']}` | `{after['config_hash']}` |")
    add("")

    if sweep:
        add("## Sweep (2026-12-01)")
        add("")
        add("| Metric | Value |")
        add("|---|---|")
        add(f"| active trips, peak | {sweep['active']['peak']} |")
        add(f"| active trips, median | {sweep['active']['median']} |")
        add(f"| active 00:00-05:00, peak | {sweep['active_00_05']['peak']} |")
        add(f"| positions off-polyline | {sweep['off_polyline_positions']} |")
        add(f"| continuity violations | {sweep['continuity_violations']} |")
        add(
            f"| legs over printed max +10% | {sweep['legs']['over_printed_max_10pct']} "
            f"of {sweep['legs']['with_printed_max']} |"
        )
        add(f"| benchmark median ms | {sweep['benchmark_ms']['median']} |")
        add("")

    if coverage:
        add("## Coverage")
        add("")
        add(
            f"**{coverage['shown_by_default']}** of **{coverage['total_trips']}** "
            "trips are shown by default."
        )
        add("")
        add("| Reason | Trips |")
        add("|---|---|")
        for reason, counts in coverage["hidden_by_reason"].items():
            add(f"| `{reason}` | {sum(counts.values())} |")
        add("")
        add(f"Trips still never shown: **{len(coverage['never_shown'])}**.")
        add("")

    DOCS.mkdir(parents=True, exist_ok=True)
    target = DOCS / "phase5d_report.md"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
