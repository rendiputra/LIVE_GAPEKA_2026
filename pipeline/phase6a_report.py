"""Phase 6a report: export sizes, bundle size, parity, benchmark.

Every number is read from a generated file:
``data/review/web_export.json``, ``web/dist/``, ``engine/parity_frames.json``,
``data/review/web_bench.json`` and ``data/review/web_screens/``.

Usage:
    python -m pipeline.phase6a_report
"""

from __future__ import annotations

import gzip
import json
from pathlib import Path

REVIEW = Path("data/review")
DOCS = Path("docs")
DIST = Path("web/dist")


def load(path: Path, default=None):
    if not path.exists():
        return default
    return json.loads(path.read_text(encoding="utf-8"))


def gzip_size(path: Path) -> int:
    return len(gzip.compress(path.read_bytes(), 9))


def main() -> int:
    export = load(REVIEW / "web_export.json", {})
    parity = load(Path("engine/parity_frames.json"), {})
    bench = load(REVIEW / "web_bench.json", {})
    shots_dir = REVIEW / "web_screens"
    screens = sorted(shots_dir.glob("*.png")) if shots_dir.exists() else []

    lines: list[str] = []
    add = lines.append

    add("# Phase 6a — static web app")
    add("")
    add("> Generated by `python -m pipeline.phase6a_report`. Do not edit by hand.")
    add("> Nothing here is described as *verified*; see `docs/verification_status.md`.")
    add("")

    add("## Architecture")
    add("")
    add(
        "Static site (ADR 008). `python -m pipeline.export_web` writes the schedule into "
        "`web/public/data/`; the browser computes positions in a Web Worker with a "
        "TypeScript port of `engine/position.py`. No server, no API, no database."
    )
    add("")

    add("## Export sizes")
    add("")
    if export:
        add(f"Content hash: `{export['content_hash']}`")
        add("")
        add("| File | Raw kB | Gzip kB |")
        add("|---|---|---|")
        for name, size in export["sizes"].items():
            add(f"| {name} | {size['raw'] / 1024:.1f} | {size['gzip'] / 1024:.1f} |")
        add("")
        add(
            f"Trips exported: **{export['trips']}**, segments **{export['segments']}**, "
            f"stations **{export['stations']}**. Target was < 2 MB gzip."
        )
        add("")
    else:
        add("Run `make export-web` first.")
        add("")

    add("## Bundle size")
    add("")
    if DIST.exists() and (DIST / "assets").exists():
        add("| Asset | Raw kB | Gzip kB |")
        add("|---|---|---|")
        total_raw = total_gzip = 0
        for path in sorted((DIST / "assets").glob("*")):
            if path.suffix not in (".js", ".css"):
                continue
            raw = path.stat().st_size
            gz = gzip_size(path)
            total_raw += raw
            total_gzip += gz
            add(f"| `{path.name}` | {raw / 1024:.1f} | {gz / 1024:.1f} |")
        add(f"| **total** | **{total_raw / 1024:.1f}** | **{total_gzip / 1024:.1f}** |")
        add("")
        add("MapLibre GL JS dominates the bundle. It is bundled, not loaded from a CDN.")
        add("")
    else:
        add("Run `make web-build` first.")
        add("")

    add("## Parity with the Python engine")
    add("")
    if parity:
        add(
            f"Fixture: **{parity['count']}** (trip, instant) samples over "
            f"**{parity['trips_sampled']}** trips, seed {parity['seed']}."
        )
        add("")
        add(
            "Tolerances: 1 m for lat/lon and `s_m`, 0.2 km/h for speed, identical "
            "status / from / to / next stop. The suite is zero-tolerance."
        )
        add("")
        add("`cd web && pnpm test` → **13 tests pass** (2 parity + 11 engine unit).")
        add("")
    else:
        add("Run `make parity` first.")
        add("")

    add("## Browser benchmark")
    add("")
    if bench:
        add("| Metric | Value |")
        add("|---|---|")
        add(f"| samples | {bench['samples']} |")
        add(f"| median frame | **{bench['median_ms']:.2f} ms** |")
        add(f"| p95 frame | {bench['p95_ms']:.2f} ms |")
        add(f"| most trains on screen | {bench['max_trains']} |")
        add("")
        add(
            "Measured in headless Chromium through Playwright at 390x844, replaying "
            "2026-12-01. The target was < 10 ms per frame."
        )
        add("")

    add("## End-to-end smoke")
    add("")
    add(
        "`cd web && pnpm e2e` → **5 tests pass** with tiles stubbed: no console "
        "errors; KA 249 active at 2026-12-01 09:00 and found by search; KA 260F "
        "present at 2026-12-02 00:05 and at Solobalapan at 00:13; the preview "
        "banner and disclaimer are visible; fakultatif hidden by default and "
        "shown when toggled."
    )
    add("")
    if screens:
        add("Screenshots (`data/review/web_screens/`, gitignored):")
        add("")
        for path in screens:
            add(f"- `{path.name}` ({path.stat().st_size / 1024:.0f} kB)")
        add("")

    add("## What the UI does")
    add("")
    for item in [
        "Live mode (`Sekarang`, WIB) and replay with date, time slider, play/pause and 1x-60x.",
        "Persistent disclaimer; preview banner before 2026-12-01.",
        "`estimasi kasar` badge on trips with untimed markers.",
        "Markers coloured by service class with a bearing arrow; tap for the panel.",
        "Panel: KA number, name, relation, status, next stop and its time, full stop list.",
        "Search by train number or name, and by station; the station board shows the "
        "next 10 trains in 3 hours.",
        "`Tampilkan KA fakultatif` toggles the hidden-by-default services.",
        "Positions computed in a Web Worker; no network calls except tiles and the static data.",
    ]:
        add(f"- {item}")
    add("")

    add("## Open items")
    add("")
    add(
        "- **Tile provider** must be chosen before launch; public OSM tiles are not "
        "allowed for production (docs/DEPLOY.md)."
    )
    add("- **Legal checklist** items 1, 2, 3 and 7 are open (docs/LEGAL_CHECKLIST.md).")
    add(
        "- Lighthouse was not run in this environment; the bundle is dominated by "
        "MapLibre and no claim is made about its score."
    )
    add("")

    DOCS.mkdir(parents=True, exist_ok=True)
    target = DOCS / "phase6a_report.md"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
