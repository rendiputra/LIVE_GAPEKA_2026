"""Generate docs/phase4_report.md from the geometry artefacts.

Usage:
    python -m pipeline.phase4_report
"""

from __future__ import annotations

import json
import time
from pathlib import Path

from pipeline.build_geometry import build, load_config

DOCS = Path("docs")
REVIEW = Path("data/review")
PARSED = Path("data/parsed")
EXTERNAL = Path("data/external")


def load(path: Path, default):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else default


def render(payload: dict, v: dict, manifest: list) -> str:
    lines: list[str] = []
    add = lines.append
    graph = payload["graph"]
    cfg = payload["config"]
    osm = next((m for m in manifest if m["source"] == "geofabrik_java"), {})

    add("# Phase 4 — Rail geometry")
    add("")
    add("> Generated by `python -m pipeline.phase4_report`. Do not edit by hand.")
    add("> Nothing here is *verified*; see `docs/verification_status.md`.")
    add("")

    add("## Source")
    add("")
    add(f"- Geofabrik Java extract, retrieved {osm.get('retrieved', 'unknown')}")
    add(f"- PBF SHA-256 `{osm.get('pbf_sha256', 'unknown')}`")
    add(f"- Licence: {osm.get('license', 'ODbL')}")
    add(
        "- Chosen over Overpass because Overpass returned HTTP 502/504 repeatedly; "
        "a hash-pinned snapshot is reproducible."
    )
    add("")

    add("## Graph")
    add("")
    add(f"- nodes: **{graph['nodes']:,}**")
    add(f"- edges: **{graph['edges']:,}**")
    add(
        f"- gap bridges added (endpoints < {cfg['gap_bridge_m']:.0f} m apart): "
        f"**{graph['gap_bridges']}**"
    )
    add("")

    add("## Construction corrections (evidence-driven)")
    add("")
    add("Two defects were found by measurement and fixed; both are reported rather than hidden:")
    add("")
    add(
        "1. **`railway=platform` was entering the graph** (1,074 ways). A blocklist "
        "filter let non-track ways in, splitting the network into ~1,150 components; "
        "312 of 394 segments fell back to straight lines. An allowlist "
        "(`railway=rail`) reduced this to 21 components."
    )
    add(
        "2. **`service=crossover|siding|spur` was excluded**, although on double "
        "track these are the only links between the parallel tracks. Excluding "
        "`yard` alone cut suspect segments from 88 to 8 and raised fully-routed "
        "trips from 94 to 238."
    )
    add("")

    add("## Station snapping")
    add("")
    add("| Band | Stations |")
    add("|---|---|")
    for band, count in payload["snap_bands"].items():
        add(f"| {band} | {count} |")
    add("")
    add(
        f"Thresholds: accept ≤ {cfg['snap_accept_m']:.0f} m, review ≤ "
        f"{cfg['snap_review_m']:.0f} m, above that rejected."
    )
    add("")

    add("## Segments by quality")
    add("")
    add("| Quality | Segments |")
    add("|---|---|")
    for quality, count in sorted(payload["quality_counts"].items()):
        add(f"| {quality} | {count} |")
    add("")

    add("## Trips by geometry status")
    add("")
    add("| Status | Trips |")
    add("|---|---|")
    for status, count in sorted(payload["trip_status_counts"].items()):
        add(f"| {status} | {count} |")
    add("")

    add("## V5 — connectivity")
    v5 = v["V5"]
    add(f"- pairs checked: **{v5['checked']}**")
    add(f"- trips by coverage: {v5['details'].get('trips_by_coverage', {})}")
    add(f"- non-routed pairs: **{v5['details'].get('non_routed_pairs')}**")
    add("")
    if v5["details"].get("non_routed"):
        add("| Pair | Trips affected |")
        add("|---|---|")
        for row in v5["details"]["non_routed"][:25]:
            add(f"| {row['pair']} | {row['trips_affected']} |")
        add("")

    add("## V12 — detour")
    v12 = v["V12"]
    add(f"- segments measured: **{v12['checked']}**")
    add(f"- distribution: {v12['details']}")
    add(f"- above {v12['details']['threshold']}: **{v12['finding_count']}**")
    add("")
    if v12["findings"]:
        add("| Pair | Ratio | Straight m | Routed m |")
        add("|---|---|---|---|")
        for row in v12["findings"][:25]:
            add(
                f"| {row['pair']} | {row['detour_ratio']} | "
                f"{row['straight_m']} | {row['length_m']} |"
            )
        add("")

    add("## V13 — implied speed (evidence for Phase 5)")
    v13 = v["V13"]
    add(f"- timed hops measured: **{v13['checked']}**")
    add(f"- average km/h: {v13['details']['avg_kmh']}")
    add(f"- average km/h ÷ printed maximum: {v13['details']['ratio_avg_to_printed']}")
    add(f"- hops above 1.0× printed: **{v13['details']['above_1_0']}**")
    add(
        f"- hops above {v13['details']['thresholds']['fast_kmh']:.0f} km/h: "
        f"**{v13['details']['above_fast']}**"
    )
    add(
        f"- hops below {v13['details']['thresholds']['slow_kmh']:.0f} km/h: "
        f"**{v13['details']['below_slow']}**"
    )
    add("")
    add(
        "The printed **Kecepatan Maksimum** column behaves like a section limit, not "
        "an average: the median hop runs at ~0.6× of it. That is evidence only — the "
        "column's physical meaning is not assumed here."
    )
    add("")
    if v13["findings"]:
        add("| Train | From | To | s | m | km/h | printed | ratio |")
        add("|---|---|---|---|---|---|---|---|")
        for row in v13["findings"][:25]:
            add(
                f"| {row['train_no']} | {row['from']} | {row['to']} | {row['seconds']} | "
                f"{row['length_m']} | {row['avg_kmh']} | {row['printed_max']} | {row['ratio']} |"
            )
        add("")

    add("## V14 — cumulative consistency")
    v14 = v["V14"]
    add(f"- segments checked: **{v14['checked']}**")
    add(f"- non-positive segments: **{v14['finding_count']}**")
    add(f"- pairs with no segment row: **{v14['details']['pairs_without_segment_row']}**")
    add("")

    add("## Review page")
    add("")
    add(
        "`data/review/geometry_review.html` — stations by snap band, every "
        "non-routed/suspect segment, and the full routes of KA 249, 250, 259F, 260F, "
        "1 and one long-distance train chosen deterministically (the longest fully "
        "routed non-pilot trip)."
    )
    add("")

    add("## Runtime")
    add("")
    add(f"- geometry build: **{payload['runtime_seconds']}s**")
    add(f"- segment content hash: `{payload['content_hash']}`")
    add("")

    add("## Limitations")
    add("")
    for item in [
        "Book 1 + Book 2 only; KRL and freight are untouched.",
        "344 trips still contain an unmeasured pair, all because a station has no "
        "accepted coordinate (6 rejected, 11 missing) or failed to snap.",
        "8 suspect segments and 2 straight-line fallbacks remain and are flagged.",
        "The printed speed column meaning is still unconfirmed; V13 is evidence, not a gate.",
        "Gap bridging (18 synthetic edges) is a topology repair, not surveyed track.",
        "No human has compared any route against imagery yet.",
    ]:
        add(f"- {item}")
    add("")
    return "\n".join(lines) + "\n"


def main() -> int:
    started = time.time()
    payload = build(load_config())
    from pipeline.validators_phase4 import run as run_validators

    v = run_validators(payload["config"])
    manifest = load(EXTERNAL / "manifest.json", [])
    DOCS.mkdir(parents=True, exist_ok=True)
    (DOCS / "phase4_report.md").write_text(render(payload, v, manifest), encoding="utf-8")
    (REVIEW / "phase4_validators.json").write_text(json.dumps(v, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {DOCS / 'phase4_report.md'} in {time.time() - started:.1f}s")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
