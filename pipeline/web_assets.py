"""T5: self-host the basemap glyphs and sprites.

The Protomaps style references fonts and sprites from a GitHub Pages CDN. The
site must not depend on a runtime CDN, so this downloads exactly the assets the
style needs into ``web/public/tiles/assets/`` (gitignored) and records a manifest.

Only the Latin ranges are fetched: Java place names are Latin script, so the
Devanagari font stack in the style is never requested.

Usage:
    python -m pipeline.web_assets
"""

from __future__ import annotations

import json
import sys
import urllib.error
import urllib.request
from pathlib import Path

ASSET_HOST = "https://protomaps.github.io/basemaps-assets"
OUT_DIR = Path("web/public/tiles/assets")
MANIFEST = OUT_DIR / "manifest.json"

FONT_STACKS = ("Noto Sans Regular", "Noto Sans Italic")
# Latin + punctuation ranges. MapLibre asks for 256-glyph blocks.
RANGES = (
    "0-255",
    "256-511",
    "512-767",
    "768-1023",
    "1024-1279",
    "1280-1535",
    "1536-1791",
    "1792-2047",
    "2048-2303",
    "2304-2559",
    "8192-8447",
    "8448-8703",
)
SPRITES = ("light.json", "light.png", "light@2x.json", "light@2x.png")
SPRITE_DIR = "sprites/v4"


def fetch(url: str, target: Path, timeout: int = 60) -> int:
    target.parent.mkdir(parents=True, exist_ok=True)
    with urllib.request.urlopen(url, timeout=timeout) as response:  # noqa: S310
        payload = response.read()
    target.write_bytes(payload)
    return len(payload)


def download(out_dir: Path = OUT_DIR) -> dict:
    files: list[dict] = []
    total = 0

    for stack in FONT_STACKS:
        quoted = stack.replace(" ", "%20")
        for glyph_range in RANGES:
            url = f"{ASSET_HOST}/fonts/{quoted}/{glyph_range}.pbf"
            target = out_dir / "fonts" / stack / f"{glyph_range}.pbf"
            try:
                size = fetch(url, target)
            except (urllib.error.URLError, urllib.error.HTTPError) as error:
                raise RuntimeError(f"failed to fetch {url}: {error}") from error
            files.append({"path": str(target.relative_to(out_dir)), "bytes": size})
            total += size

    for name in SPRITES:
        url = f"{ASSET_HOST}/{SPRITE_DIR}/{name}"
        target = out_dir / "sprites" / name
        try:
            size = fetch(url, target)
        except (urllib.error.URLError, urllib.error.HTTPError) as error:
            raise RuntimeError(f"failed to fetch {url}: {error}") from error
        files.append({"path": str(target.relative_to(out_dir)), "bytes": size})
        total += size

    manifest = {
        "source": ASSET_HOST,
        "font_stacks": list(FONT_STACKS),
        "ranges": list(RANGES),
        "sprites": list(SPRITES),
        "files": len(files),
        "bytes": total,
        "megabytes": round(total / 1e6, 2),
        "note": (
            "Self-hosted so the site has no runtime CDN. Generated by `make basemap`; gitignored."
        ),
    }
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest


def main() -> int:
    try:
        manifest = download()
    except RuntimeError as error:
        print(f"ASSETS FAILED: {error}", file=sys.stderr)
        return 1
    print(f"wrote {OUT_DIR}")
    print(f"  {manifest['files']} files, {manifest['megabytes']} MB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
