"""Generate docs/phase4d_report.md from generated artefacts only.

Every number in the report is read from a file: `data/review/t1_before.json`
(reproduced with `python -m pipeline.build_geometry --baseline`),
`data/review/t1_after.json`, `data/parsed/segments.json` and
`data/review/db_build.json`.

Usage:
    python -m pipeline.phase4d_report
"""

from __future__ import annotations

import json
from pathlib import Path

REVIEW = Path("data/review")
DOCS = Path("docs")


def load(path: Path, default=None):
    if not path.exists():
        return default
    return json.loads(path.read_text(encoding="utf-8"))


def blocked_per_book(payload: dict) -> dict[str, int]:
    counts: dict[str, int] = {}
    for key, entry in payload.get("trip_status", {}).items():
        if entry.get("status") != "has_unmeasured":
            continue
        book = key.split(":", 1)[0]
        counts[book] = counts.get(book, 0) + 1
    return counts


def row(label: str, before, after) -> str:
    return f"| {label} | {before} | {after} |"


def main() -> int:
    before = load(REVIEW / "t1_before.json")
    after = load(REVIEW / "t1_after.json")
    segments = load(Path("data/parsed/segments.json"), {})
    db = load(REVIEW / "db_build.json", {})
    q1 = load(REVIEW / "q1_bridge_candidates.json", {})
    q3 = load(REVIEW / "q3_triple_rail.json", {})
    q3c = load(REVIEW / "q3_vs_a3.json", {})
    q4 = load(REVIEW / "a4_bypass_candidates.json", {})

    if not before or not after:
        print("run build_geometry (and --baseline) and the T1 step first")
        return 2

    lines: list[str] = []
    add = lines.append

    add("# Phase 4d — Q1-Q4, H3 and the T1 rebuild")
    add("")
    add("> Generated by `python -m pipeline.phase4d_report`. Do not edit by hand.")
    add("> The *before* column comes from `data/review/t1_before.json`, produced by")
    add("> `python -m pipeline.build_geometry --baseline`, which disables the human")
    add("> bridges (Q1) and the waypoint bypass (Q4). The *after* column comes from")
    add("> `data/review/t1_after.json`.")
    add("")

    add("## Segment quality")
    add("")
    add("| Quality | Before | After |")
    add("|---|---|---|")
    bq = before["quality_counts"]
    aq = after["segment_quality"]
    for quality in sorted(set(bq) | set(aq)):
        add(row(f"`{quality}`", bq.get(quality, 0), aq.get(quality, 0)))
    add(row("**total**", sum(bq.values()), sum(aq.values())))
    add("")

    add("## Trip geometry status")
    add("")
    add("| Status | Before | After |")
    add("|---|---|---|")
    bt = before["trip_status_counts"]
    at = after["trip_status"]
    for status in sorted(set(bt) | set(at)):
        add(row(f"`{status}`", bt.get(status, 0), at.get(status, 0)))
    add(row("**total**", sum(bt.values()), sum(at.values())))
    add("")

    add("## Trips blocked by `has_unmeasured`, per book")
    add("")
    bb = blocked_per_book(before)
    ab = after.get("blocked", {})
    add("| Book | Before | After |")
    add("|---|---|---|")
    for book in sorted(set(bb) | set(ab), key=str):
        add(row(f"Book {book}", bb.get(book, 0), ab.get(book, 0)))
    add("")

    add("## Station coordinate status")
    add("")
    add(
        "Q1-Q4 and H3 changed no station coordinate (H3 was report-only), so this "
        "table is unchanged. It is reproduced from `data/review/t1_after.json`."
    )
    add("")
    add("| coord_status | Stations |")
    add("|---|---|")
    for status, count in sorted(after["coord_status"].items()):
        add(f"| `{status}` | {count} |")
    add("")

    add("## Bypassed waypoints (Q4)")
    add("")
    add(
        f"`trip_waypoint_estimates` holds **{after['bypass_rows']}** rows, one per "
        "bypassed waypoint. Bypassing is allowed only for `pass`/`unknown_untimed` "
        "rows whose station has no accepted coordinate, with located neighbours and "
        "at most 3 consecutive rows."
    )
    add("")
    if q4:
        add("Stations without an accepted coordinate, and their row types:")
        add("")
        stations = q4.get("stations") or []
        if stations:
            add("| Code | Name | pass rows | stop rows | trains affected |")
            add("|---|---|---|---|---|")
            for entry in stations:
                rows_by_type = entry.get("rows_by_type", {})
                add(
                    f"| `{entry.get('code')}` | {entry.get('name', '')} | "
                    f"{rows_by_type.get('pass', 0)} | {rows_by_type.get('stop', 0)} | "
                    f"{entry.get('trains_affected', '')} |"
                )
            add("")
            add(
                "A `stop` row is never bypassed, so `RO` (one `stop` row) keeps that "
                "trip blocked while its 29 pass-only trips are bypassed."
            )
            add("")
        else:
            add("See `data/review/a4_bypass_candidates.json`.")
            add("")

    add("## Neighbour-consistency triples (Q3, rail-path)")
    add("")
    if q3:
        counts = q3.get("counts", {})
        add(
            f"**{sum(counts.values())}** triples evaluated on the routed rail graph: "
            f"{counts.get('ok', 0)} ok, **{counts.get('failure', 0)}** failures, "
            f"{counts.get('junction_turnback', 0)} `junction_turnback` (info)."
        )
        add("")
        if q3c:
            add(
                f"The superseded straight-line test (`data/review/a3_coord_hygiene.json`) "
                f"flagged **{q3c['old_straight_line_entries']}** triples over "
                f"{q3c['old_unique_codes']} distinct stations. The rail-path test clears "
                f"**{q3c['old_flagged_now_ok_count']}** of those stations as false "
                "positives, and adds no new failure that the old test had missed."
            )
            add("")
        failures = q3.get("failures", [])
        if failures:
            add("| Code | Triple | Ratio | Turn angle |")
            add("|---|---|---|---|")
            for entry in failures:
                add(
                    f"| `{entry['code']}` | {entry['via']} | {entry['ratio']} | "
                    f"{entry['turn_angle_deg']}° |"
                )
            add("")
        turnbacks = q3.get("junction_turnbacks", [])
        if turnbacks:
            add("Classified `junction_turnback` (information, not failure):")
            add("")
            add("| Code | Triple | Ratio | Turn angle |")
            add("|---|---|---|---|")
            for entry in turnbacks:
                add(
                    f"| `{entry['code']}` | {entry['via']} | {entry['ratio']} | "
                    f"{entry['turn_angle_deg']}° |"
                )
            add("")

    add("## Bridges reported but not applied (Q1 side report)")
    add("")
    if q1:
        for threshold, data in q1.get("thresholds", {}).items():
            add(f"- at **{threshold}**: {data['count']} disconnected components would bridge")
        add("")
        five = q1.get("thresholds", {}).get("5m", {}).get("components", [])
        if five:
            add("| Component size | Gap (m) | from node | to node |")
            add("|---|---|---|---|")
            for entry in five:
                add(
                    f"| {entry['component_size']} | {entry['gap_m']} | "
                    f"`{entry['from']}` | `{entry['to']}` |"
                )
            add("")

    add("## Content hashes")
    add("")
    add("| Artefact | Hash |")
    add("|---|---|")
    add(f"| baseline segments (not applied) | `{before['content_hash']}` |")
    add(f"| current segments | `{segments.get('content_hash')}` |")
    add(f"| database | `{db.get('content_hash')}` |")
    add("")
    add("The baseline hash differs from the current one by construction; it is recorded")
    add("so the comparison is reproducible, not because it is used anywhere.")
    add("")

    add("## Database row counts")
    add("")
    add("| Table | Rows |")
    add("|---|---|")
    for table, count in db.get("counts", {}).items():
        add(f"| `{table}` | {count} |")
    add("")

    DOCS.mkdir(parents=True, exist_ok=True)
    target = DOCS / "phase4d_report.md"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
