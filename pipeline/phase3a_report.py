"""Generate docs/phase3a_report.md from the built database and review artefacts.

Every number here is read from files the pipeline produced, so the report cannot
drift from the data.

Usage:
    python -m pipeline.phase3a_report
"""

from __future__ import annotations

import json
import time
from pathlib import Path

from pipeline.build_db import build
from pipeline.cell_markers import describe as marker_describe
from pipeline.cross_checks import run as run_cross_checks
from pipeline.match_stations import run as run_station_matching

DOCS = Path("docs")
REVIEW = Path("data/review")
DB = Path("data/gapeka.db")


def load(path: Path, default):
    if not path.exists():
        return default
    return json.loads(path.read_text(encoding="utf-8"))


def book2_v4_list() -> dict:
    """The Book 2 V4 'parsed but not in index' list, with header text and page."""
    v4 = load(REVIEW / "phase2_v4.json", {})
    parsed = load(Path("data/parsed/local_trips.json"), {"trains": []})
    by_no = {t["train_no"]: t for t in parsed["trains"] if t["train_no"]}
    rows = []
    for number in v4.get("in_tables_not_in_index", []):
        train = by_no.get(number)
        if train is None:
            rows.append({"train_no": number, "page": None, "header": None})
            continue
        rows.append(
            {
                "train_no": number,
                "page": train["page"],
                "header": f"KA {number} ({train['name']}) {train['origin']}-{train['destination']}",
            }
        )
    return {"count": len(rows), "rows": rows}


def render(summary: dict, stations: dict, cross: dict, marker_cfg: dict) -> str:
    lines: list[str] = []
    add = lines.append

    add("# Phase 3a — MVP assembly")
    add("")
    add("> Generated by `python -m pipeline.phase3a_report`. Do not edit by hand.")
    add("> Nothing here is described as *verified*; see `docs/verification_status.md`.")
    add("")
    add("## Scope")
    add("")
    add(
        "Book 1 (intercity) and Book 2 (local) only. KRL and freight are explicitly "
        "out of scope (AGENTS.md Phase 3b)."
    )
    add("")

    add("## Database")
    add("")
    add("| Table | Rows |")
    add("|---|---|")
    for table, count in summary["counts"].items():
        add(f"| {table} | {count:,} |")
    add("")
    add(f"- content hash: `{summary['content_hash']}`")
    add("- rebuild is deterministic: the same input produces the same hash")
    add(f"- stations with coordinates: **{summary['stations_with_coordinates']:,}**")
    add(
        f"- trips with untimed markers (`has_untimed_markers`): "
        f"**{summary['trips_with_untimed_markers']}**"
    )
    add("")

    add("## Loaded vs skipped")
    add("")
    add(f"- loaded trips: **{summary['counts']['trips']:,}**")
    add(f"- skipped: **{summary['skipped']}**")
    add("")
    skipped = load(REVIEW / "db_skipped.json", {"trains": []})
    if skipped["trains"]:
        add("| Book | Train | Reason |")
        add("|---|---|---|")
        for row in skipped["trains"][:40]:
            add(f"| {row['book']} | {row['train_no']} | {row['reason']} |")
        add("")
    else:
        add("Nothing was skipped: every parsed train in scope passed the gate.")
        add("")

    add("## Calendar policy")
    add("")
    add("Per ADR 002 and the human ruling:")
    add("")
    add("| service_class | service_pattern | pattern_source |")
    add("|---|---|---|")
    add("| reguler | `daily` | `assumed` |")
    add("| fakultatif | null | `unknown` |")
    add("| unknown | null | `unknown` |")
    add("")
    add("`daily` is an **assumption**, not a document fact: the PDF states no weekday pattern.")
    add("")
    add("| service_class | Trips |")
    add("|---|---|")
    for key, value in summary["service_class"].items():
        add(f"| {key} | {value} |")
    add("")

    add("## Cell markers (ADR 003)")
    add("")
    add(f"- enabled: {', '.join(f'`{t}`' for t in marker_cfg['enabled']) or 'none'}")
    add(
        f"- observed but NOT enabled: "
        f"{', '.join(f'`{t}`' for t in marker_cfg['observed_not_enabled']) or 'none'}"
    )
    add(
        "- a marker row has `time = null`, `time_source = marker`, a preserved raw "
        "token, and `stop_type = unknown_untimed`"
    )
    add("")

    add("## Untimed-marker distribution")
    add("")
    untimed = load(REVIEW / "untimed_distribution.json", {"trains": []})
    if untimed["trains"]:
        runs: dict[int, int] = {}
        for row in untimed["trains"]:
            runs[row["longest_run"]] = runs.get(row["longest_run"], 0) + 1
        add("| Longest consecutive untimed run | Trains |")
        add("|---|---|")
        for run in sorted(runs):
            add(f"| {run} | {runs[run]} |")
        add("")
        add(f"- trains with at least one untimed row: **{len(untimed['trains'])}**")
        add(f"- untimed rows in total: **{untimed['total_untimed_rows']}**")
        add("- these trips are labelled **coarser estimate** (ADR 003)")
        add("")
    else:
        add("No untimed rows in the loaded slice.")
        add("")

    add("## Stations")
    add("")
    add("| Metric | Value |")
    add("|---|---|")
    add(f"| PDF station codes | {stations['pdf_stations']:,} |")
    add(f"| matched to a coordinate | {stations['matched']:,} |")
    add(f"| unmatched | {stations['unmatched']} |")
    add(f"| ambiguous (multiple candidates) | {stations['ambiguous']} |")
    add(f"| suspicious coordinates | {stations.get('suspicious', 0)} |")
    add("")
    add("| Match method | Stations |")
    add("|---|---|")
    for method, count in stations.get("by_method", {}).items():
        add(f"| `{method}` | {count} |")
    add("")
    add(
        "Coordinates come from Wikidata (CC0) first, then OpenStreetMap (ODbL). "
        "Nothing is guessed or interpolated; see `docs/DATA_SOURCES.md`."
    )
    add("")

    unmatched = load(REVIEW / "stations_unmatched.json", {"stations": []})
    if unmatched["stations"]:
        add("### Unmatched")
        add("")
        add("| Code | Printed name | Pages | Trains |")
        add("|---|---|---|---|")
        for row in unmatched["stations"]:
            add(f"| {row['code']} | {row['name']} | {row['page_count']} | {row['train_count']} |")
        add("")

    ambiguous = load(REVIEW / "stations_ambiguous.json", {"stations": []})
    if ambiguous["stations"]:
        add("### Ambiguous")
        add("")
        add("| Code | Printed name | Reason | Candidates |")
        add("|---|---|---|---|")
        for row in ambiguous["stations"]:
            add(f"| {row['code']} | {row['name']} | {row['reason']} | {len(row['candidates'])} |")
        add("")

    suspicious = load(REVIEW / "stations_suspicious_coords.json", {"stations": []})
    if suspicious["stations"]:
        add("### Suspicious coordinates")
        add("")
        add("| Codes | Reason | Detail |")
        add("|---|---|---|")
        for row in suspicious["stations"]:
            detail = (
                row.get("reason")
                or f"neighbours {row['neighbours']} at {row['neighbour_distances_km']} km"
            )
            add(f"| {row['code']} | {detail} | `{row['source_id']}` |")
        add("")

    add("## Distance sanity")
    add("")
    distance = cross["distance"]
    add(f"- consecutive stop pairs measured: **{distance['pairs_measured']:,}**")
    add(f"- pairs missing coordinates: **{distance['pairs_missing_coordinates']}**")
    add(
        f"- outliers beyond {distance['outlier_threshold_km']:.0f} km: "
        f"**{distance['outlier_count']}**"
    )
    add("")
    add(
        "A long straight-line gap is either a genuine non-stop express run or a wrong "
        "coordinate. Both are listed, not judged."
    )
    add("")
    add("| Train | From | To | km |")
    add("|---|---|---|---|")
    for row in distance["outliers"][:15]:
        add(f"| {row['train_no']} | {row['from']} | {row['to']} | {row['km']} |")
    add("")

    add("## Cross-book findings")
    add("")
    cb = cross["cross_book"]
    add(f"- Book 1 trains: **{cb['book1_trains']}**")
    add(f"- Book 2 trains: **{cb['book2_trains']}**")
    add(f"- train numbers appearing in BOTH books: **{cb['train_numbers_in_both_count']}**")
    if cb["train_numbers_in_both_books"]:
        add(f"  - {', '.join(cb['train_numbers_in_both'][:40])}")
    add(
        f"- identical (train_no, relation, first departure) signatures: "
        f"**{cb['identical_signature_count']}**"
    )
    add(f"- multi-number trains: **{cb['multi_number_count']}**")
    add("")
    add(f"`trip_id` is deterministic: `{cb['trip_id_rule']}`.")
    add("")

    add("## Book 2 V4 — parsed but not in the index")
    add("")
    b2 = book2_v4_list()
    add(
        f"{b2['count']} train numbers are parsed from tables but absent from the "
        "Book 2 index. Reported only; nothing is resolved."
    )
    add("")
    add("| Train | Page | Table header |")
    add("|---|---|---|")
    for row in b2["rows"]:
        add(f"| {row['train_no']} | {row['page']} | {row['header']} |")
    add("")

    add("## Smoke queries")
    add("")
    add("Documented in `docs/SMOKE_QUERIES.md`; all three run against the built database.")
    add("")

    add("## Runtime")
    add("")
    add(f"- build + report: **{summary['runtime_seconds']:.1f}s**")
    add("")

    add("## Limitations")
    add("")
    for limitation in summary["limitations"]:
        add(f"- {limitation}")
    add("")

    return "\n".join(lines) + "\n"


def main() -> int:
    started = time.time()
    summary = build(DB)
    stations = run_station_matching()
    cross = run_cross_checks()
    marker_cfg = marker_describe()

    summary["runtime_seconds"] = time.time() - started
    summary["limitations"] = [
        "Book 1 and Book 2 only; KRL and freight are not parsed (Phase 3b).",
        "No review sample has been compared against the PDF by a human yet.",
        "Coordinates are external and unverified; 4 suspicious/duplicate points are listed.",
        "Calendar 'daily' for reguler is an assumption, not a document fact (ADR 002).",
        "11 station codes with stops have no coordinate, so their segments cannot be measured.",
        "Berh/Sb marker trips carry coarser position estimates (ADR 003).",
        "V2 speed thresholds remain unset until Phase 4 provides distances.",
    ]

    DOCS.mkdir(parents=True, exist_ok=True)
    (DOCS / "phase3a_report.md").write_text(
        render(summary, stations, cross, marker_cfg), encoding="utf-8"
    )
    print(f"wrote {DOCS / 'phase3a_report.md'}")
    print(
        json.dumps(
            {
                "trips": summary["counts"]["trips"],
                "stop_times": summary["counts"]["stop_times"],
                "hash": summary["content_hash"],
                "stations_matched": stations["matched"],
                "outliers": cross["distance"]["outlier_count"],
            },
            indent=2,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
