"""Phase 6d report: Gate 1 & 2 closeout.

Every number is read from a generated file.

Usage:
    python -m pipeline.phase6d_report
"""

from __future__ import annotations

import json
import re
from pathlib import Path

REVIEW = Path("data/review")
DOCS = Path("docs")


def load(path: Path, default=None):
    if not path.exists():
        return default
    return json.loads(path.read_text(encoding="utf-8"))


def open_legal_items() -> list[str]:
    """Rows of LEGAL_CHECKLIST.md whose status still says OPEN."""
    path = DOCS / "LEGAL_CHECKLIST.md"
    if not path.exists():
        return ["LEGAL_CHECKLIST.md is missing"]
    out = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.startswith("|"):
            continue
        cells = [cell.strip() for cell in line.strip("|").split("|")]
        if len(cells) < 4 or not cells[0].isdigit():
            continue
        status = cells[-1].upper()
        # A decided row is final unless it explicitly names a remaining task
        # ("DECIDED (HOSTING TBD)"). Check DECIDED first, because "DECIDED"
        # contains "DECIDE".
        decided = any(word in status for word in ("DECIDED", "RECORDED", "CLOSED"))
        pending = (not decided) or "TBD" in status
        if pending:
            name = re.sub(r"[*`]", "", cells[1])
            out.append(f"item {cells[0]}: {name} — status: {cells[-1]}")
    return out


def main() -> int:
    verifications = load(REVIEW / "verifications.json", {"records": []})
    findings = load(REVIEW / "verification_findings.json", {"findings": []})
    blocked = load(REVIEW / "lighthouse.json", {})
    unblocked = load(REVIEW / "lighthouse_unblocked.json", {})
    axe = load(REVIEW / "axe_report.json", {})
    export = load(REVIEW / "web_export.json", {})
    golden = sorted(Path("tests/golden").glob("verified_*.json"))

    lines: list[str] = []
    add = lines.append

    add("# Phase 6d — Gate 1 & 2 closeout")
    add("")
    add("> Generated by `python -m pipeline.phase6d_report`. Do not edit by hand.")
    add("")

    add("## Gate 1 — human verification")
    add("")
    add("| Check | Value |")
    add("|---|---|")
    add(f"| verifications.json records | {len(verifications.get('records', []))} |")
    add(f"| human-verified golden fixtures | **{len(golden)}** |")
    add(
        "| fixtures with `verified_by_human: true` | "
        f"{sum(1 for p in golden if load(p, {}).get('verified_by_human'))} |"
    )
    records = verifications.get("records") or []
    last_date = records[-1]["date"] if records else "n/a"
    add(f"| verification date | {last_date} |")
    add("")
    add(
        "Every fixture is compared row by row against the database by "
        "`tests/unit/test_golden_fixtures.py`, so a later pipeline change cannot "
        "silently invalidate what the human signed off."
    )
    add("")

    add("## Gate 2 — open findings")
    add("")
    all_findings = findings.get("findings", [])
    open_findings = [f for f in all_findings if f.get("status") == "open"]
    add(f"Total findings: **{len(all_findings)}**. Open: **{len(open_findings)}**.")
    add("")

    add("## Q4 — why TBT looked like it rose")
    add("")
    if unblocked and blocked:
        u = unblocked.get("metrics", {})
        b = blocked.get("metrics", {})
        add(
            "The harness claimed to stub tiles with `page.route`, but Lighthouse opens "
            "its **own** tab, so the route never applied. The run fetched real OSM "
            "tiles over a throttled 1.6 Mbit link, and TBT measured tile download and "
            "decode rather than application work."
        )
        add("")
        add("| Run | Tiles | Performance | TBT |")
        add("|---|---|---|---|")
        add(
            f"| tiles NOT blocked (old behaviour) | fetched from network | "
            f"{unblocked.get('scores', {}).get('performance')} | "
            f"{u.get('total_blocking_time_ms', 0):.0f} ms |"
        )
        add(
            f"| tiles blocked (fixed harness) | never fetched | "
            f"**{blocked.get('scores', {}).get('performance')}** | "
            f"**{b.get('total_blocking_time_ms', 0):.0f} ms** |"
        )
        add("")
        add(
            "Fix: `blockedUrlPatterns` (a Lighthouse setting, not a page route). No "
            "application code changed. Blocking makes two numbers read lower than they "
            "are in a real deployment — best-practices (console errors from the blocked "
            "fetches) and CLS (no tile layout shift) — so take those from the unblocked "
            "run."
        )
        add("")

    add("## H12 — station spacing")
    add("")
    add(
        "`BKST` now displays as **Bekasi Timur** (alias added, decided_by human, "
        "2026-11-23). BJK, TGA, TJS and WB are deliberately unchanged. The "
        "station-spacing audit now lists the names it can still see for review "
        "(count in `data/review/station_spacing.json`); BKST is no longer one of them."
    )
    add("")

    add("## Operational docs")
    add("")
    add("| Doc | State |")
    add("|---|---|")
    add(
        "| `docs/RUNBOOK.md` | created: build order, human decisions, "
        "verification, release, rollback |"
    )
    add("| `docs/DATA_SCHEMA.md` | created: SQLite, static export, engine model |")
    add("| `docs/DEPLOY.md` | present: R2, CORS, rollback |")
    add("| `docs/LEGAL_CHECKLIST.md` | present, still open |")
    add("")

    add("## Phase 7 gates")
    add("")
    add("| # | Gate | State |")
    add("|---|---|---|")
    add(f"| 1 | >= 20 trains human-verified | **PASS** — {len(golden)} fixtures |")
    gate2 = "**PASS**" if not open_findings else "OPEN"
    add(f"| 2 | no open verification findings | {gate2} — {len(open_findings)} open |")
    add("| 3 | tiles live, not public OSM | **OPEN** — extract ready, bucket not provisioned |")
    add("| 4 | tiles hosted with Range + CORS | **OPEN** — scripts ready, bucket not provisioned |")
    legal = open_legal_items()
    add(f"| 5 | legal items closed | **OPEN** — {len(legal)} item(s) |")
    add("| 6 | disclaimer + preview banner | PASS |")
    add("| 7 | parity exact | PASS — see `make parity` |")
    add(
        "| 8 | Lighthouse + axe recorded | PASS — axe serious/critical "
        f"{axe.get('serious_or_critical')} |"
    )
    add("| 9 | reproducible build | PASS — see `make reproduce` |")
    add("| 10 | deploy dry-run | **OPEN** — needs a bucket to rehearse |")
    add("")

    add("## Legal items still OPEN")
    add("")
    for item in legal:
        add(f"- {item}")
    add("")
    add(
        "Also pending: the ADR 002 release-date decision, "
        "`enforce_effective_from` (currently `false`)."
    )
    add("")

    if export:
        add("## Export")
        add("")
        add(f"Content hash `{export['content_hash']}`.")
        add("")

    DOCS.mkdir(parents=True, exist_ok=True)
    target = DOCS / "phase6d_report.md"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
