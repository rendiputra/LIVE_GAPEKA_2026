"""Phase 5b report: H5/H6 outcomes, T1 before/after, F-d findings, T3 blockers.

Every number is read from a generated file:

- ``data/review/t1_after.json`` (the Phase 4d state, BEFORE this round)
- ``data/review/t1_5b_after.json`` (AFTER this round)
- ``data/review/h5_h6_gate.json``
- ``data/review/r1_engine_sweep.json``
- ``data/review/coverage_blockers.json``
- ``data/review/q3_triple_rail.json``

Usage:
    python -m pipeline.phase5b_report
"""

from __future__ import annotations

import json
from pathlib import Path

REVIEW = Path("data/review")
DOCS = Path("docs")


def load(path: Path, default=None):
    if not path.exists():
        return default
    return json.loads(path.read_text(encoding="utf-8"))


def table(add, title: str, before: dict, after: dict, label: str) -> None:
    add(f"## {title}")
    add("")
    add(f"| {label} | Before | After |")
    add("|---|---|---|")
    for key in sorted(set(before) | set(after)):
        add(f"| `{key}` | {before.get(key, 0)} | {after.get(key, 0)} |")
    add(f"| **total** | {sum(before.values())} | {sum(after.values())} |")
    add("")


def main() -> int:
    before = load(REVIEW / "t1_after.json")
    after = load(REVIEW / "t1_5b_after.json")
    gate = load(REVIEW / "h5_h6_gate.json", {})
    sweep = load(REVIEW / "r1_engine_sweep.json", {})
    coverage = load(REVIEW / "coverage_blockers.json", {})
    q3 = load(REVIEW / "q3_triple_rail.json", {})

    if not before or not after:
        print("missing t1_after.json / t1_5b_after.json")
        return 2

    lines: list[str] = []
    add = lines.append

    add("# Phase 5b — H5/H6, suspect segments, coverage")
    add("")
    add("> Generated by `python -m pipeline.phase5b_report`. Do not edit by hand.")
    add("> Nothing here is described as *verified*; see `docs/verification_status.md`.")
    add("")

    add("## What changed")
    add("")
    add(
        "- **H6 SRI applied**: the Wikidata coordinate snapped 1,806 m from rail and "
        "blocked KA 249/250. The rail-path gate passed (snap 1.4 m, triple ratio 1.000), "
        "so the override was applied and KA 249/250 now load."
    )
    add(
        "- **H5 TLM NOT applied**: the coordinate is right, but `snap()` picks a parallel "
        "track 3.1 m nearer that routes 2.8x too far. Applying it now would make geometry "
        "worse, so it is a proposal only."
    )
    add(
        "- **Q3 turn-back rule corrected**: the threshold was inverted. A genuine "
        "turn-back has its two neighbours on the SAME side of B (small angle); the old "
        "`>= 150 deg` rule excused in-line pass-throughs instead."
    )
    add(
        "- **Segment reviews (ADR 005)**: a human `accept_route` turns `osm_suspect` into "
        "`osm_routed_reviewed` and counts as complete. The file is empty; no decision "
        "was taken by the pipeline."
    )
    add("- **Replay (F-a) fixed**: frames now come from `positions_at` over 30 hours.")
    add("")

    table(
        add,
        "T1 — Station coordinate status",
        before["coord_status"],
        after["coord_status"],
        "coord_status",
    )
    table(
        add,
        "T1 — Segment quality",
        before["segment_quality"],
        after["segment_quality"],
        "quality",
    )
    table(
        add,
        "T1 — Trip geometry status",
        before["trip_status"],
        after["trip_status"],
        "status",
    )
    table(
        add,
        "T1 — Trips blocked by has_unmeasured, per book",
        before["blocked"],
        after["blocked"],
        "book",
    )

    add("## T1 — Headline counts")
    add("")
    add("| Metric | Before | After |")
    add("|---|---|---|")
    add(
        f"| trips shown by default | {before.get('shown_by_default', 'n/a')} | "
        f"**{after['shown_by_default']}** |"
    )
    add(
        f"| trips loaded by the engine | {before.get('trips_loaded_by_engine', 'n/a')} | "
        f"**{after['trips_loaded_by_engine']}** |"
    )
    add(f"| bypassed waypoint rows | {before.get('bypass_rows')} | {after.get('bypass_rows')} |")
    add(
        f"| stations with coordinates | {before.get('stations_with_coordinates', 'n/a')} | "
        f"{after.get('stations_with_coordinates')} |"
    )
    add("")

    add("## T1 — Content hashes")
    add("")
    add("| Artefact | Before | After |")
    add("|---|---|---|")
    add(f"| segments | `{before.get('segments_hash')}` | `{after.get('segments_hash')}` |")
    add(f"| database | `{before.get('db_hash')}` | `{after.get('db_hash')}` |")
    add("")

    add("## H5 / H6 gate results")
    add("")
    if gate:
        add("| Code | Outcome | Snap (m) | Triple ratio | Turn angle | Note |")
        add("|---|---|---|---|---|---|")
        for row in gate.get("results", []):
            add(
                f"| `{row['code']}` | **{row['outcome']}** | {row.get('snap_m')} | "
                f"{row.get('ratio')} | {row.get('angle')} | {row.get('note', '')} |"
            )
        add("")
        add(
            "The gate enumerates every rail edge within the snap threshold, because a "
            "station between two tracks is within a few metres of both."
        )
        add("")
    else:
        add("See `data/review/h5_h6_gate.json`.")
        add("")

    add("## F-d — suspect segments and over-speed legs")
    add("")
    if sweep:
        legs = sweep["legs"]
        add(
            f"{legs['over_printed_max_10pct']} of {legs['with_printed_max']} timed legs "
            "imply a cruise speed more than 10% above the printed maximum."
        )
        add("")
        add("| Ratio bucket | Legs |")
        add("|---|---|")
        for bucket, count in legs["cruise_to_printed_ratio_buckets"].items():
            add(f"| {bucket} | {count} |")
        add("")
    add(
        "Root cause of the `MSG <-> BTT` cases: the routed `BTT-CS` line is far too long "
        "because `BTT` snaps to a stub. Routing from the adjacent way gives ~4.95 km "
        "instead of 11.54 km. It is a SNAP problem, not a missing way; the draft bridge "
        "file records it as such."
    )
    add("")

    add("## T3 — Coverage blockers")
    add("")
    if coverage:
        add(
            f"Of **{coverage['total_trips']}** trips, "
            f"**{coverage['shown_by_default']}** are shown by default."
        )
        add("")
        add("| Reason | Trips |")
        add("|---|---|")
        for reason, counts in coverage["hidden_by_reason"].items():
            add(f"| `{reason}` | {sum(counts.values())} |")
        add("")
        add("Top blockers by greedy marginal gain:")
        add("")
        add("| Unblocks | Touches | Blocker |")
        add("|---|---|---|")
        for row in coverage["top_blockers"][:20]:
            add(f"| {row['marginal_unblocked']} | {row['trips_touching']} | {row['label']} |")
        add("")
    add("## Q3 — rail-path triples")
    add("")
    if q3:
        counts = q3["counts"]
        add(
            f"{sum(counts.values())} triples: {counts.get('ok', 0)} ok, "
            f"**{counts.get('failure', 0)}** failures, "
            f"{counts.get('junction_turnback', 0)} `junction_turnback`."
        )
        add("")
        add("| Code | Triple | Ratio | Angle |")
        add("|---|---|---|---|")
        for row in q3.get("failures", []):
            add(f"| `{row['code']}` | {row['via']} | {row['ratio']} | {row['turn_angle_deg']}° |")
        add("")

    add("## Open defect — midnight-straddling stops")
    add("")
    add(
        "12 `stop_times` rows arrive before midnight and depart after it, and one "
        "`day_offset` per row cannot represent that. The parser gives the row "
        "`day_offset = 1`, which pushes the ARRIVAL a day late. In the replay "
        "reproduction check every mismatch traces to this; there are no unexplained "
        "mismatches. This is reported, not silently patched."
    )
    add("")

    DOCS.mkdir(parents=True, exist_ok=True)
    target = DOCS / "phase5b_report.md"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
